#!/usr/bin/env python3
"""One-prime modular lower-bound certificates dim g_L > 2L(4L-1) for L = 5 and 10..31.

Wave-18 LadderW8 front, part (b) of the all-L free-fermion no-go for the
two-generator ladder pair

    A_L = sum_v X_v,   B_L = sum_{(u,v) in E(2xL)} Z_u Z_v,
    g_L = <A_L, B_L>_Lie  over Q.

If A_L and B_L were simultaneously quadratic in one set of 4L Majorana
operators on the physical (C^2)^(2L), then (both operators are traceless, so
no identity component can appear) g_L would embed in the image of so(4L),
of dimension 2L(4L-1) = 8L^2 - 2L.  The no-go at a given L therefore needs

    dim_Q g_L  >=  8L^2 - 2L + 1  =: tau(L) + 1.

The companion producer experiments/e173_ladder_nogo_family.py proves an
explicit lower bound Q(L) > tau(L) for every L >= 32 (partition-family
theorem, proofs/ladder_w8.md).  The certified evaluation bounds
dim g_L >= K_L - W_L cover 6 <= L <= 9 (494, 1780, 6562, 24566), and exact
closures cover L = 3, 4 (263, 2952).  This script certifies the remaining
band: L = 5 and L = 10..31.

Two engines, both standard repository technology:

  (E1) L = 5: literal Pauli word closure.  Greedy BFS over divided brackets
       [X_v, Q_(a|b)]/2 = +Q_(a^e_v|b) iff b_v = 1 and
       [Z_uZ_v, Q_(a|b)]/2 = -Q_(a|b^m) iff |a & m| odd, in the integral
       Q_(a|b) = X^a Z^b convention, sparse echelon over F_p,
       p = 2147483647, early stop at the target rank.  A modular rank of an
       integral family is a characteristic-zero lower bound.

  (E2) L = 10..31: sector-capped state-space evaluation.  All operators
       P_k B P_k' (sector projectors are Lagrange polynomials in A_L, so
       these lie in the associative algebra generated by A_L and B_L) are
       applied to the vacuum psi = |+>^(2L), storing only the even sectors
       0, 2, 4 of the <tau,rho>-invariant orbit-sum basis.  Every stored
       vector is an integral vector of U(A,B) psi reduced mod q = 999983;
       the modular rank of the family lower-bounds dim_Q U(A,B) psi, and
       the evaluation bound (Theorem 2, proofs/ladder_alll_proof.md) gives
       dim_Q g_L >= dim_Q U(A,B) psi.  Early stop at rank tau(L) + 1.

Budgeting: process_time per L with explicit caps; peak RSS recorded.  A
budget stop is recorded as NON-DECISIVE for that L (never a theorem).

Usage:
  PYTHONPATH=src .venv/bin/python experiments/e174_ladder_gap_certificates.py
"""
