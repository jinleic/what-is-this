# (E2) sector-capped state-space evaluation certificates.
# ---------------------------------------------------------------------------
def canon(cfg: tuple, L: int) -> tuple:
    best = None
    for f in range(4):
        im = []
        for v in cfg:
            w = v
            if f & 1:
                w ^= 1
            if f & 2:
                w = 2 * (L - 1 - (w >> 1)) + (w & 1)
            im.append(w)
        t = tuple(sorted(im))
        if best is None or t < best:
            best = t
    return best


def enum_orbits(L: int, k: int):
    idx = {}
    reps = []
    sizes = []
    for cfg in combinations(range(2 * L), k):
        ims = set()
        for f in range(4):
            im = []
            for v in cfg:
                w = v
                if f & 1:
                    w ^= 1
                if f & 2:
                    w = 2 * (L - 1 - (w >> 1)) + (w & 1)
                im.append(w)
            ims.add(tuple(sorted(im)))
        rep = min(ims)
        if rep == cfg:
            idx[rep] = len(reps)
            reps.append(rep)
            sizes.append(len(ims))
    return reps, idx, sizes


class CSR:
    __slots__ = ("indptr", "cols", "dat", "shape")

    def __init__(self, rows, cols, dat, shape):
        order = np.lexsort((cols, rows))
        r = np.array(rows, dtype=np.int64)[order]
        c = np.array(cols, dtype=np.int64)[order]
        d = np.array(dat, dtype=np.int64)[order]
        indptr = np.zeros(shape[0] + 1, dtype=np.int64)
        np.add.at(indptr, r + 1, 1)
        np.cumsum(indptr, out=indptr)
        self.indptr = indptr
        self.cols = c
        self.dat = d
        self.shape = shape

    def rowvec_mul(self, sidx, svals, q, out):
        out[:] = 0
        for j in range(sidx.size):
            i = int(sidx[j])
            v = int(svals[j])
            lo, hi = self.indptr[i], self.indptr[i + 1]
            out[self.cols[lo:hi]] += v * self.dat[lo:hi]
        out %= q
        return out


def build_block(L, reps_s, sizes_s, idx_t, sizes_t, k_target) -> CSR:
    E = edges(L)
    rows = []
    cols = []
    dat = []
    for i, cfg in enumerate(reps_s):
        cnt = Counter()
        s = set(cfg)
        for (u, v) in E:
            nc = set(s)
            for w in (u, v):
                if w in nc:
                    nc.remove(w)
                else:
                    nc.add(w)
            if len(nc) != k_target:
                continue
            cnt[canon(tuple(sorted(nc)), L)] += 1
        for rep, c in cnt.items():
            j = idx_t[rep]
            num = sizes_s[i] * c
            if num % sizes_t[j]:
                raise AssertionError("orbit integrality failed")
            rows.append(i)
            cols.append(j)
            dat.append(num // sizes_t[j])
    return CSR(rows, cols, dat, (len(reps_s), len(idx_t)))


def state_certificate(L: int, target: int, budget_s: float, q: int = Q1) -> dict:
    started = time.process_time()
    reps2, idx2, sz2 = enum_orbits(L, 2)
    reps4, idx4, sz4 = enum_orbits(L, 4)
    n2, n4 = len(reps2), len(reps4)
    B22 = build_block(L, reps2, sz2, idx2, sz2, 2)
    B24 = build_block(L, reps2, sz2, idx4, sz4, 4)
    B42 = build_block(L, reps4, sz4, idx2, sz2, 2)
    B44 = build_block(L, reps4, sz4, idx4, sz4, 4)
    build_cpu = round(time.process_time() - started, 2)
    seed = np.zeros(n2, dtype=np.int64)
    for (u, v) in edges(L):
        seed[idx2[canon((min(u, v), max(u, v)), L)]] = 1
    rows = {2: {}, 4: {}}
    scratch = {2: np.zeros(n2, dtype=np.int64), 4: np.zeros(n4, dtype=np.int64)}

    def add(sector, dense):
        w = scratch[sector]
        if dense is not w:
            w[:] = dense
        rows_s = rows[sector]
        while True:
            nz = np.nonzero(w)[0]
            if nz.size == 0:
                return None
            piv = int(nz[-1])
            got = rows_s.get(piv)
            if got is None:
                inv = pow(int(w[piv]), q - 2, q)
                rows_s[piv] = (nz.astype(np.int32), (((w[nz] * inv) % q).astype(np.int32)))
                return piv
            sidx, svals = got
            c = int(w[piv])
            w[sidx] = (w[sidx] - c * svals.astype(np.int64)) % q

    tmp = scratch[2]
    tmp[:] = seed
    todo = [(2, add(2, tmp))]
    out2 = np.zeros(n2, dtype=np.int64)
    out4 = np.zeros(n4, dtype=np.int64)

    def rank():
        return len(rows[2]) + len(rows[4]) + 1  # +1: the vacuum spans sector 0

    status = "OK"
    while todo and rank() < target:
        sector, piv = todo.pop(0)
        sidx, svals = rows[sector][piv]
        outs = ((2, B22, out2), (4, B24, out4)) if sector == 2 else ((2, B42, out2), (4, B44, out4))
        for tsec, M, out in outs:
            M.rowvec_mul(sidx, svals, q, out)
            if np.any(out):
                pp = add(tsec, out)
                if pp is not None:
                    todo.append((tsec, pp))
        if time.process_time() - started > budget_s:
            status = "BUDGET"
            break
    cpu = round(time.process_time() - started, 2)
    achieved = rank()
    return {
        "L": L,
        "engine": "sector_capped_state_closure",
        "prime": q,
        "sector_dims": {"2": n2, "4": n4},
        "target": target,
        "rank": achieved,
        "certified": achieved >= target,
        "status": status if achieved < target else "OK",
        "cpu_seconds": cpu,
        "block_build_cpu_seconds": build_cpu,
        "peak_rss_bytes": peak_rss_bytes(),
    }


def main() -> int:
    started = time.process_time()
    records = []
    checks = []

    rec5 = word_certificate(WORD_L, tau(WORD_L) + 1, 300.0)
    records.append(rec5)
    progress({"event": "word_certificate", **{k: rec5[k] for k in ("L", "rank", "target", "certified", "cpu_seconds")}})
    log(f"L=5 word certificate: rank {rec5['rank']} target {rec5['target']}")
    checks.append({
        "name": "L5_word_certificate",
        "passed": bool(rec5["certified"]),
        "detail": f"rank {rec5['rank']} >= {rec5['target']} = 8*25-10+1 at p={P1}",
    })

    for L in STATE_RANGE:
        target = tau(L) + 1
        rec = state_certificate(L, target, PER_L_BUDGET)
        records.append(rec)
        progress({"event": "state_certificate", **{k: rec[k] for k in ("L", "rank", "target", "certified", "cpu_seconds", "status")}})
        log(f"L={L}: rank {rec['rank']} target {target} [{rec['status']}] {rec['cpu_seconds']}s")
        checks.append({
            "name": f"L{L}_state_certificate",
            "passed": bool(rec["certified"]),
            "detail": f"rank {rec['rank']} >= {target} = 8L^2-2L+1 at q={Q1}"
            if rec["certified"] else f"NON-DECISIVE budget stop at rank {rec['rank']} < {target}",
        })

    all_ok = all(c["passed"] for c in checks)
    envelope = {
        "meta": {
            "script": SCRIPT,
            "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "python": sys.version.split()[0],
            "numpy": np.__version__,
            "cpu_seconds_total": round(time.process_time() - started, 2),
            "peak_rss_bytes": peak_rss_bytes(),
            "claim": (
                "Each record is a one-prime modular lower-bound certificate "
                "dim_Q g_L >= rank (>= 8L^2-2L+1 when certified); modular rank of an "
                "integral family never exceeds the rational rank, and every stored "
                "vector lies in U(A,B)psi (sector projectors are polynomials in A_L)."
            ),
        },
        "data": {
            "targets": {str(L): tau(L) + 1 for L in (WORD_L, *STATE_RANGE)},
            "records": records,
            "checks": checks,
        },
    }
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = OUT_PATH.with_suffix(".tmp")
    tmp.write_text(json.dumps(envelope, indent=1, sort_keys=True))
    tmp.replace(OUT_PATH)
    log(f"wrote {OUT_PATH.relative_to(ROOT)}")
    print("PASS" if all_ok else "INCOMPLETE (see NON-DECISIVE rows)")
    return 0 if all_ok else 1

def assemble() -> int:
    """Consolidate the three wave-18 LadderW8 sub-artifacts into
    results/algebra_growth/ladder_w8.json (meta + data + checks envelope)."""
    reg = json.loads((ROOT / "results" / "algebra_growth" / "ladder_w8_regression.json").read_text())
    fam = json.loads((ROOT / "results" / "algebra_growth" / "ladder_w8_family.json").read_text())
    cert = json.loads(OUT_PATH.read_text())
    checks = []
    for name, art in (("regression", reg), ("family", fam), ("certificates", cert)):
        for c in art["data"]["checks"]:
            checks.append({"name": f"{name}:{c['name']}", "passed": c["passed"], "detail": c["detail"]})
    recs = {r["L"]: r for r in cert["data"]["records"]}
    nogo_rows = []
    nogo_rows.append({"L": 2, "bound": 11, "threshold": tau(2), "verdict": "INCONCLUSIVE (11 <= 28; ring TFIM)",
                      "source": "results/algebra_growth/profiles.json (ring 3n-1)"})
    nogo_rows.append({"L": 3, "bound": 263, "threshold": tau(3), "verdict": "EXCLUDED",
                      "source": "exact closure, notes/algebra_growth.md"})
    nogo_rows.append({"L": 4, "bound": 2952, "threshold": tau(4), "verdict": "EXCLUDED",
                      "source": "exact closure H255, proofs/char0_complete_2x4.md"})
    nogo_rows.append({"L": 5, "bound": recs[5]["rank"], "threshold": tau(5), "verdict": "EXCLUDED",
                      "source": "this artifact (word certificate)"})
    for L, val in ((6, 494), (7, 1780), (8, 6562), (9, 24566)):
        nogo_rows.append({"L": L, "bound": val, "threshold": tau(L), "verdict": "EXCLUDED",
                          "source": "K_L - W_L sandwich certificates (waves 14-16)"})
    for L in STATE_RANGE:
        nogo_rows.append({"L": L, "bound": recs[L]["rank"], "threshold": tau(L),
                          "verdict": "EXCLUDED" if recs[L]["certified"] else "NON-DECISIVE",
                          "source": "this artifact (state certificate)"})
    nogo_rows.append({"L": ">=32", "bound": "Q(L)", "threshold": "8L^2-2L",
                      "verdict": "EXCLUDED (partition-family theorem)",
                      "source": "results/algebra_growth/ladder_w8_family.json + proofs/ladder_w8.md sec. 4-5"})
    ok_all = all(c["passed"] for c in checks)
    checks.append({
        "name": "nogo_all_rows_decided",
        "passed": all(r["verdict"].startswith("EXCLUDED") for r in nogo_rows if r["L"] != 2),
        "detail": "every L >= 3 row EXCLUDED; L = 2 honestly inconclusive",
    })
    envelope = {
        "meta": {
            "script": SCRIPT + " --assemble",
            "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "components": [
                "results/algebra_growth/ladder_w8_regression.json",
                "results/algebra_growth/ladder_w8_family.json",
                "results/algebra_growth/ladder_w8_certificates.json",
            ],
            "theorem": (
                "For every L >= 3 the pair (A_L, B_L) on the open 2xL ladder is not "
                "simultaneously Majorana-quadratic on the physical 2^(2L)-dimensional space: "
                "dim_Q <A_L,B_L>_Lie > 2L(4L-1).  L = 2 is honestly inconclusive by this route."
            ),
            "proof_note": "proofs/ladder_w8.md",
        },
        "data": {
            "nogo_table": nogo_rows,
            "law_conjecture": reg["data"]["law"],
            "recurrence_audit": reg["data"]["recurrence_audit"],
            "rss_remediation": {
                "issue": (
                    "initial single-process sweeps over L = 10..31 peaked at 5.53 GB (producer) "
                    "and 5.75 GB (verifier) cumulative RSS on the tail rows, above the ~4 GB wave budget; "
                    "per-row peaks recorded in ladder_w8_certificates.json; ranks unaffected"
                ),
                "fix": "echelon rows stored as int32 pairs (q = 999983 < 2^31); reductions upcast to int64",
                "fixed_engine_measurements": [
                    {"L": 20, "rank": 3161, "certified": True, "cpu_seconds": 113.18,
                     "isolated_peak_rss_gb": 0.28},
                    {"L": 31, "rank": 7627, "certified": True, "cpu_seconds": 1133.63,
                     "isolated_peak_rss_gb": 2.81},
                ],
                "note": "fixed-engine ranks identical to the shipped certificates at both probes",
            },
            "checks": checks,
        },
    }
    out = ROOT / "results" / "algebra_growth" / "ladder_w8.json"
    tmp = out.with_suffix(".tmp")
    tmp.write_text(json.dumps(envelope, indent=1, sort_keys=True))
    tmp.replace(out)
    log(f"wrote {out.relative_to(ROOT)}")
    print("PASS" if all(c["passed"] for c in checks) and ok_all else "FAIL")
    return 0 if all(c["passed"] for c in checks) and ok_all else 1


