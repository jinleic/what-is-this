P1 = 2_147_483_647
Q1 = 999_983
WORD_L = 5
STATE_RANGE = tuple(range(10, 32))
PER_L_BUDGET = 12000.0


def tau(L: int) -> int:
    return 8 * L * L - 2 * L


def peak_rss_bytes() -> int:
    value = int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    return value if sys.platform == "darwin" else value * 1024


def log(msg: str) -> None:
    print(f"[e174 {time.strftime('%H:%M:%S')}] {msg}", flush=True)


def progress(event: dict) -> None:
    PROGRESS.parent.mkdir(parents=True, exist_ok=True)
    with PROGRESS.open("a") as handle:
        handle.write(json.dumps(event, sort_keys=True) + "\n")


def edges(L: int) -> list[tuple[int, int]]:
    E = [(2 * r, 2 * r + 1) for r in range(L)]
    for r in range(L - 1):
        E += [(2 * r, 2 * r + 2), (2 * r + 1, 2 * r + 3)]
    return E


# ---------------------------------------------------------------------------
# (E1) literal Pauli word closure with early stop.
# ---------------------------------------------------------------------------
def word_certificate(L: int, target: int, budget_s: float, prime: int = P1) -> dict:
    started = time.process_time()
    n = 2 * L
    masks = [(1 << u) | (1 << v) for (u, v) in edges(L)]
    A = {(1 << v, 0): 1 for v in range(n)}
    B = {(0, m): 1 for m in masks}

    def bracket_A(X: dict) -> dict:
        out: dict = {}
        for (a, b), c in X.items():
            bb = b
            while bb:
                low = bb & -bb
                bb ^= low
                key = (a ^ low, b)
                out[key] = (out.get(key, 0) + c) % prime
        return {k: v for k, v in out.items() if v}

    def bracket_B(X: dict) -> dict:
        out: dict = {}
        for (a, b), c in X.items():
            for m in masks:
                if bin(a & m).count("1") & 1:
                    key = (a, b ^ m)
                    out[key] = (out.get(key, 0) - c) % prime
        return {k: v for k, v in out.items() if v}

    rows: dict = {}

    def add(vec: dict):
        v = dict(vec)
        while v:
            piv = max(v)
            got = rows.get(piv)
            if got is None:
                inv = pow(v[piv], prime - 2, prime)
                rows[piv] = {k: val * inv % prime for k, val in v.items()}
                return piv
            c = v[piv]
            for k, val in got.items():
                nv = (v.get(k, 0) - c * val) % prime
                if nv:
                    v[k] = nv
                elif k in v:
                    del v[k]
        return None

    todo = []
    for g in (A, B):
        if add(g) is not None:
            todo.append(dict(g))
    processed = 0
    status = "OK"
    while todo and len(rows) < target:
        base = todo.pop(0)
        processed += 1
        for br in (bracket_A, bracket_B):
            img = br(base)
            if img and add(img) is not None:
                todo.append(img)
                if len(rows) >= target:
                    break
        if time.process_time() - started > budget_s:
            status = "BUDGET"
            break
    cpu = round(time.process_time() - started, 2)
    return {
        "L": L,
        "engine": "pauli_word_closure",
        "prime": prime,
        "target": target,
        "rank": len(rows),
        "certified": len(rows) >= target,
        "status": status if len(rows) < target else "OK",
        "words_processed": processed,
        "cpu_seconds": cpu,
    }


