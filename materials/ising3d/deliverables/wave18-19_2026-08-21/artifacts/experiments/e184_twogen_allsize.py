#!/usr/bin/env python3
"""Integrate the two-generator all-size attempt, counterexamples, and exact wall."""

from __future__ import annotations

import hashlib
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from e182_adA_spectrum import (
    RSS_CAP_BYTES,
    max_rss_bytes,
    run_spectrum_audit,
)
from e183_twogen_closure import run_closure_audit

ROOT = Path(__file__).resolve().parents[1]
ARTIFACT = ROOT / "results" / "algebra_growth" / "twogen_allsize.json"
CPU_BUDGET_SECONDS = 1_800.0

EXACT_Q_REFERENCES = {
    "open_2x2_and_2x3": ROOT / "results" / "algebra_structure" / "char0_levi.json",
    "open_2x4": ROOT / "results" / "algebra_structure" / "char0_complete_2x4.json",
    "open_3x3": ROOT / "results" / "algebra_structure" / "char0_3x3.json",
}
PROOF_REFERENCES = {
    "local_term_trichotomy": ROOT / "proofs" / "clifford_grade_classification.md",
    "two_by_L_all_size": ROOT / "proofs" / "ladder_w8.md",
    "three_by_L_finite": ROOT / "proofs" / "dla_3xl.md",
    "spectral_pair_product": ROOT / "proofs" / "allsize_gaussian.md",
    "spectral_2x6": ROOT / "proofs" / "gaussian_2x6.md",
}


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run_all() -> tuple[dict[str, object], list[dict[str, object]]]:
    started = time.process_time()
    spectrum, spectrum_checks = run_spectrum_audit()
    closure, closure_checks = run_closure_audit(include_anchors=True)

    complete_cases = {
        row["graph"]: row for row in closure["complete_bipartite_cases"]
    }
    anchors = {row["label"]: row for row in closure["grid_anchors"]}
    census = {
        row["n_vertices"]: row
        for row in closure["small_hamiltonian_census"]["rows"]
    }

    headline = {
        "tag": "[THEOREM — counterexamples][UNRESOLVED — eventual threshold]",
        "achieved_statement": (
            "Branching plus a bipartite Hamiltonian path does not by itself force the "
            "two-sum algebra above so(2n): K_{2,3} has dimension 44<45 at n=5 and "
            "K_{3,3} has dimension 63<66 at n=6."
        ),
        "counterexamples": [
            {
                "graph": label,
                "n_vertices": complete_cases[label]["n_vertices"],
                "dimension_Q": complete_cases[label]["rational_closure"]["dimension_Q"],
                "quadratic_ceiling": complete_cases[label]["quadratic_ceiling"],
                "bipartite": True,
                "hamiltonian_path": complete_cases[label]["hamiltonian_path"],
                "maximum_degree": complete_cases[label]["maximum_degree"],
            }
            for label in ("K_{2,3}", "K_{3,3}")
        ],
        "n0_status": {
            "exact_n0": None,
            "status": "[UNRESOLVED]",
            "proved_constraint": "if a universal eventual threshold exists, n0>=7",
            "finite_positive_size": (
                "Every one of the 63 fixed-path chord graphs at n=7 clears 91 modulo the "
                "good prime; this is a finite census and is not an induction."
            ),
            "not_proved": (
                "Neither existence nor nonexistence of an eventual universal n0 is proved."
            ),
        },
        "contrast_with_local_terms": (
            "The exact local-term branching trichotomy is cited, not reproved: it concerns the "
            "algebra generated by every X_v and ZZ_e separately.  It does not transfer to the "
            "two highly symmetric sums A and B."
        ),
    }

    separation = {
        "tag": "[LEMMA][THEOREM — refuted method]",
        "grade_preservation": (
            "D=ad_(iA) is the exterior action of a grade-two Clifford element and preserves "
            "every Clifford grade."
        ),
        "spectrum": spectrum["grade_spectrum_formula"],
        "vandermonde_lemma": (
            "For a diagonalizable D and v=sum_lambda v_lambda, the distinct-eigenvalue "
            "Vandermonde matrix recovers each v_lambda from v,Dv,...; if several grades "
            "share lambda, it recovers only their sum at that lambda."
        ),
        "decisive_collision": spectrum["collision_obstruction"],
        "three_global_components": spectrum["edge_projectors"],
        "failed_step": (
            "B_high is not obtained.  Every polynomial in D treats every path bond and chord "
            "through the same three endpoint rotations, so subtracting a recovered B_high to "
            "obtain the grade-two path part is unavailable.  Consequently the requested "
            "all-size independent-string family cannot be derived by this route."
        ),
    }

    grid_scope = {
        "tag": "[THEOREM][COMPUTATION][EXTERNAL]",
        "physical_reading": (
            "The fixed-basis dimension obstruction is graph-specific, not a consequence of "
            "branching alone: open grids clear it in every proved case, whereas complete "
            "bipartite graphs furnish the small symmetric counterexamples."
        ),
        "fresh_raw_anchor_reproduction": [anchors[label] for label in anchors],
        "external_all_size_family": {
            "family": "open 2xL grids",
            "scope": "every L>=3",
            "statement": "dim_Q <A_L,B_L> > 2L(4L-1)",
            "source": "proofs/ladder_w8.md, H460-H462",
            "ownership": "LadderW8; cited without rederivation",
            "exception": "L=2 has dimension 11<=28 and is not excluded by dimension",
        },
        "external_nonladder_finite_case": {
            "family": "open 3xL grids",
            "proved_rows": {
                "L=2": "dimension_Q=263 (grid transposition)",
                "L=3": "dimension_Q=8034",
                "L=4": "dimension_Q>=1242>276 (complete depth-15 modular minor)",
            },
            "source": "proofs/dla_3xl.md, H245-H247; exact 3x3 upgrade in proofs/char0_3x3.md",
            "unresolved": "all L>=5 and all wider rectangular grids",
        },
        "target_grid_conjecture": {
            "tag": "[CONJECTURE]",
            "statement": (
                "Every open a x b grid with a,b>=2 and ab>=6 has "
                "dim <A,B> > ab(2ab-1)."
            ),
            "proved_here_or_cited": "all 2xL, L>=3; 3x2, 3x3, 3x4",
            "unresolved": "3xL for L>=5 and min(a,b)>=4",
        },
    }

    consequence = {
        "tag": "[LEMMA][THEOREM — scoped corollary]",
        "dimension_lemma": (
            "A fixed simultaneous realization of iA and iB as bilinears in the physical 2n "
            "Majoranas puts their generated Lie algebra inside so(2n), whose dimension is "
            "n(2n-1)."
        ),
        "corollary": (
            "For every graph row whose certified lower bound exceeds n(2n-1), the displayed "
            "transfer factorization V=exp(K* A) exp(K B) is not a standard free-fermion "
            "factorization in one fixed physical Majorana basis."
        ),
        "counterexample_scope": (
            "Dimensions 44 and 63 below the ceiling do not prove that K_{2,3} or K_{3,3} is "
            "free-fermionic; the dimension test is simply inconclusive there."
        ),
        "not_a_spectral_statement": (
            "The argument constrains the pair (A,B), not the spectrum of one product.  It does "
            "not exclude V at one coupling, or its spectrum, from being Gaussian after an "
            "unrelated or coupling-dependent conjugacy.  The independent spectral certificates "
            "are proofs/allsize_gaussian.md and proofs/gaussian_2x6.md."
        ),
        "not_a_3d_solution": True,
    }

    checks = list(spectrum_checks) + list(closure_checks)
    checks.extend(
        [
            {
                "name": "headline exact counterexamples",
                "passed": (
                    complete_cases["K_{2,3}"]["rational_closure"]["dimension_Q"] == 44
                    and complete_cases["K_{3,3}"]["rational_closure"]["dimension_Q"] == 63
                ),
                "detail": "44<45 and 63<66",
            },
            {
                "name": "finite n=7 scope guard",
                "passed": (
                    census[7]["branching_graph_count"] == 63
                    and census[7]["cases_clearing_ceiling"] == 63
                    and headline["n0_status"]["exact_n0"] is None
                ),
                "detail": "finite census retained; no n0=7 claim",
            },
            {
                "name": "raw grid anchor dimensions",
                "passed": [
                    anchors[label]["certified_dimension_Q"]
                    for label in ("open_2x2", "open_2x3", "open_2x4", "open_3x3")
                ]
                == [11, 263, 2952, 8034],
                "detail": "2x2 is the genuine dimension-method exception",
            },
            {
                "name": "all cited exact-Q artifacts exist",
                "passed": all(path.is_file() for path in EXACT_Q_REFERENCES.values()),
                "detail": ", ".join(str(path.relative_to(ROOT)) for path in EXACT_Q_REFERENCES.values()),
            },
            {
                "name": "all cited proof notes exist",
                "passed": all(path.is_file() for path in PROOF_REFERENCES.values()),
                "detail": ", ".join(str(path.relative_to(ROOT)) for path in PROOF_REFERENCES.values()),
            },
            {
                "name": "resource cap",
                "passed": max_rss_bytes() < RSS_CAP_BYTES,
                "detail": f"peak_rss_bytes={max_rss_bytes()}",
            },
        ]
    )
    if not all(bool(row["passed"]) for row in checks):
        raise AssertionError("integrated two-generator audit failed")
    elapsed = time.process_time() - started
    if elapsed > CPU_BUDGET_SECONDS:
        raise RuntimeError(
            f"NON-DECISIVE process-time expiry: {elapsed:.3f}s > {CPU_BUDGET_SECONDS:.3f}s"
        )
    data = {
        "headline": headline,
        "ad_A_grade_separation": separation,
        "closure_computations": closure,
        "grid_scope": grid_scope,
        "transfer_operator_consequence": consequence,
        "process_time_seconds": round(elapsed, 6),
        "peak_rss_bytes": max_rss_bytes(),
    }
    return data, checks


def make_artifact(data: dict[str, object], checks: list[dict[str, object]]) -> dict[str, object]:
    sources = [
        ROOT / "experiments" / "e182_adA_spectrum.py",
        ROOT / "experiments" / "e183_twogen_closure.py",
        Path(__file__),
        *EXACT_Q_REFERENCES.values(),
        *PROOF_REFERENCES.values(),
    ]
    return {
        "meta": {
            "experiment": "e184_twogen_allsize",
            "generated_utc": datetime.now(timezone.utc).isoformat(),
            "command": ".venv/bin/python experiments/e184_twogen_allsize.py",
            "working_directory": str(Path.cwd()),
            "python_executable": sys.executable,
            "python_version": sys.version,
            "platform": platform.platform(),
            "machine": platform.machine(),
            "arithmetic": (
                "integers, fractions.Fraction, exact packed-Pauli commutators, and raw nested "
                "integer words modulo the good prime; timings are noncertifying"
            ),
            "budgets": {
                "process_time_seconds": CPU_BUDGET_SECONDS,
                "rss_cap_bytes": RSS_CAP_BYTES,
            },
            "source_sha256": {
                str(path.relative_to(ROOT)): sha256_file(path) for path in sources
            },
        },
        "data": data,
        "checks": checks,
    }


def main() -> int:
    data, checks = run_all()
    artifact = make_artifact(data, checks)
    ARTIFACT.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT.write_text(json.dumps(artifact, indent=2, sort_keys=True) + "\n")
    print(f"wrote {ARTIFACT.relative_to(ROOT)}")
    print(
        json.dumps(
            {
                "checks": len(checks),
                "process_time_seconds": data["process_time_seconds"],
                "peak_rss_bytes": data["peak_rss_bytes"],
            },
            sort_keys=True,
        )
    )
    print("PASS e184 two-generator all-size obstruction and counterexamples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
