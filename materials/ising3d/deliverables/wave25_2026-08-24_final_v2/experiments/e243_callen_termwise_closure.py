#!/usr/bin/env python3
"""Exact obstruction to termwise-local compression of Callen identities.

For a connected six-regular simple graph, the nonzero one- and three-neighbour
terms in the degree-six Callen identity force the minimal termwise-closed
support family generated by one two-point correlator to contain every even
proper subset.  Translation quotienting therefore remains exponential on
periodic cubic boxes.
"""

