CPU_BUDGET_SECONDS = 120.0
RSS_LIMIT_BYTES = 2 * 1024**3


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def peak_rss_bytes() -> int:
    raw = int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    return raw if platform.system() == "Darwin" else raw * 1024


def neighbours_from_edges(order: int, edges: list[tuple[int, int]]) -> tuple[tuple[int, ...], ...]:
    adjacency = [set() for _ in range(order)]
    for left, right in edges:
        if left == right:
            raise ValueError("loops are excluded")
        adjacency[left].add(right)
        adjacency[right].add(left)
    return tuple(tuple(sorted(row)) for row in adjacency)


def complete_graph(order: int) -> tuple[tuple[int, ...], ...]:
    return tuple(tuple(vertex for vertex in range(order) if vertex != site) for site in range(order))


def k8_minus_matching() -> tuple[tuple[int, ...], ...]:
    omitted = {tuple(sorted(edge)) for edge in ((0, 1), (2, 3), (4, 5), (6, 7))}
    edges = [
        (left, right)
        for left in range(8)
        for right in range(left + 1, 8)
        if (left, right) not in omitted
    ]
    return neighbours_from_edges(8, edges)


def periodic_cubic(shape: tuple[int, int, int]) -> tuple[tuple[int, ...], ...]:
    if any(length < 3 for length in shape):
        raise ValueError("periodic cubic sides must be at least three for a simple six-regular graph")
    coordinates = tuple(itertools.product(*(range(length) for length in shape)))
    index = {coordinate: position for position, coordinate in enumerate(coordinates)}
    edges: set[tuple[int, int]] = set()
    for coordinate in coordinates:
        for axis, length in enumerate(shape):
            shifted = list(coordinate)
            shifted[axis] = (shifted[axis] + 1) % length
            edge = tuple(sorted((index[coordinate], index[tuple(shifted)])))
            edges.add(edge)
    return neighbours_from_edges(len(coordinates), sorted(edges))


def connected(adjacency: tuple[tuple[int, ...], ...]) -> bool:
    seen = {0}
    queue = deque([0])
    while queue:
        vertex = queue.popleft()
        for neighbour in adjacency[vertex]:
            if neighbour not in seen:
                seen.add(neighbour)
                queue.append(neighbour)
    return len(seen) == len(adjacency)


def subset_mask(vertices: tuple[int, ...]) -> int:
    return sum(1 << vertex for vertex in vertices)


def termwise_closure(
    adjacency: tuple[tuple[int, ...], ...],
    initial: int,
    subset_sizes: tuple[int, ...] = (1, 3),
) -> set[int]:
    """Minimal family closed under A -> (A without v) symmetric_difference S."""

    family = {initial}
    queue = deque([initial])
    while queue:
        support = queue.popleft()
        for vertex in range(len(adjacency)):
            if not (support >> vertex) & 1:
                continue
            without_vertex = support ^ (1 << vertex)
            for size in subset_sizes:
                for subset in itertools.combinations(adjacency[vertex], size):
                    target = without_vertex ^ subset_mask(subset)
                    if target not in family:
                        family.add(target)
                        queue.append(target)
    return family


def token_component_size(adjacency: tuple[tuple[int, ...], ...], token_count: int) -> int:
    """Exact size of one connected component of the k-token graph."""

    start = subset_mask(tuple(range(token_count)))
    seen = {start}
    queue = deque([start])
    while queue:
        support = queue.popleft()
        for vertex, neighbours in enumerate(adjacency):
            if not (support >> vertex) & 1:
                continue
            for neighbour in neighbours:
                if (support >> neighbour) & 1:
                    continue
                target = support ^ (1 << vertex) ^ (1 << neighbour)
                if target not in seen:
                    seen.add(target)
                    queue.append(target)
    return len(seen)


def closure_cardinality(order: int) -> int:
    return (1 << (order - 1)) - (1 if order % 2 == 0 else 0)


def support_orbit_lower_bound(order: int) -> int:
    return (closure_cardinality(order) + order - 1) // order


def nontrivial_orbit_lower_bound(order: int) -> int:
    return (closure_cardinality(order) - 1 + order - 1) // order


def induction_witnesses(adjacency: tuple[tuple[int, ...], ...]) -> list[dict[str, object]]:
    """One exact k->k+2 witness at a fixed degree-six vertex for every needed k."""

    order = len(adjacency)
    vertex = 0
    triple = tuple(adjacency[vertex][:3])
    excluded = {vertex, *triple}
    available = tuple(site for site in range(order) if site not in excluded)
    largest = order - 2 if order % 2 == 0 else order - 1
    rows: list[dict[str, object]] = []
    for size in range(2, largest, 2):
        filler = available[: size - 1]
        source = (vertex, *filler)
        source_mask = subset_mask(source)
        target_mask = (source_mask ^ (1 << vertex)) ^ subset_mask(triple)
        rows.append(
            {
                "source_size": size,
                "target_size": target_mask.bit_count(),
                "pivot": vertex,
                "triple": list(triple),
                "source_excludes_triple": not any(
                    (source_mask >> neighbour) & 1 for neighbour in triple
                ),
                "target_omits_pivot": not ((target_mask >> vertex) & 1),
            }
        )
    return rows


def run() -> dict[str, object]:
    started = time.process_time()
    checks: list[dict[str, object]] = []

    coefficients = callen.local_coefficients(6)
    expected_c1 = callen.RationalFunction(
        (0, 1, 0, 16, 0, 46, 0, 16, 0, 1),
        (1, 0, 21, 0, 106, 0, 106, 0, 21, 0, 1),
    )
    expected_c3 = callen.RationalFunction(
        (0, 0, 0, -2), (1, 0, 15, 0, 15, 0, 1)
    )
    checks.append(
        {
            "name": "degree_six_Callen_coefficients",
            "passed": coefficients[1] == expected_c1 and coefficients[3] == expected_c3,
            "detail": "c1 is strictly positive and c3 strictly negative for every 0<v<1",
        }
    )

    finite_graphs = {
        "K7": complete_graph(7),
        "K8_minus_perfect_matching": k8_minus_matching(),
    }
    finite_audits: dict[str, dict[str, object]] = {}
    for name, adjacency in finite_graphs.items():
        order = len(adjacency)
        full = termwise_closure(adjacency, initial=(1 << 0) | (1 << 1))
        singleton_only = termwise_closure(
            adjacency, initial=(1 << 0) | (1 << 1), subset_sizes=(1,)
        )
        expected_supports = {
            support
            for support in range(1 << order)
            if support.bit_count() % 2 == 0 and support != (1 << order) - 1
        }
        finite_audits[name] = {
            "order": order,
            "degree_multiset": sorted(len(row) for row in adjacency),
            "connected": connected(adjacency),
            "closure_size": len(full),
            "expected_size": closure_cardinality(order),
            "closure_equals_all_even_proper_subsets": full == expected_supports,
            "singleton_only_size": len(singleton_only),
            "singleton_only_expected": math.comb(order, 2) + 1,
            "triple_terms_load_bearing": len(singleton_only) < len(full),
        }
    checks.append(
        {
            "name": "finite_exact_closure_audits",
            "passed": all(
                row["connected"]
                and row["closure_equals_all_even_proper_subsets"]
                and row["closure_size"] == row["expected_size"]
                and row["singleton_only_size"] == row["singleton_only_expected"]
                and row["triple_terms_load_bearing"]
                for row in finite_audits.values()
            ),
            "detail": "K7 gives 64 supports; K8 minus a matching gives 127; c1 alone gives only empty plus pairs",
        }
    )

    cubic = periodic_cubic((3, 3, 3))
    witnesses = induction_witnesses(cubic)
    token_counts = {
        str(tokens): token_component_size(cubic, tokens) for tokens in (2, 4)
    }
    expected_token_counts = {str(tokens): math.comb(27, tokens) for tokens in (2, 4)}
    checks.extend(
        [
            {
                "name": "periodic_3x3x3_is_connected_six_regular",
                "passed": connected(cubic)
                and len(cubic) == 27
                and all(len(row) == 6 for row in cubic),
                "detail": "27 vertices, 81 edges, six distinct neighbours per vertex",
            },
            {
                "name": "token_graph_connectivity_controls",
                "passed": token_counts == expected_token_counts,
                "detail": f"component sizes {token_counts} equal binomial totals",
            },
            {
                "name": "all_induction_witnesses",
                "passed": [row["source_size"] for row in witnesses]
                == list(range(2, 26, 2))
                and all(
                    0 <= row["pivot"] < len(cubic)
                    and len(set(row["triple"])) == 3
                    and all(
                        neighbour in cubic[row["pivot"]]
                        for neighbour in row["triple"]
                    )
                    and row["target_size"] == row["source_size"] + 2
                    and row["source_excludes_triple"]
                    and row["target_omits_pivot"]
                    for row in witnesses
                ),
                "detail": "one disjoint neighbour triple grows every even size 2 through 24",
            },
        ]
    )

    periodic_rows = []
    for shape in ((3, 3, 3), (3, 3, 4), (4, 4, 4)):
        order = math.prod(shape)
        periodic_rows.append(
            {
                "shape": list(shape),
                "order": order,
                "termwise_support_count_including_empty": str(
                    closure_cardinality(order)
                ),
                "nontrivial_correlator_support_count": str(
                    closure_cardinality(order) - 1
                ),
                "translation_group_order": order,
                "support_orbit_lower_bound_including_empty": str(
                    support_orbit_lower_bound(order)
                ),
                "nontrivial_correlator_orbit_lower_bound": str(
                    nontrivial_orbit_lower_bound(order)
                ),
                "largest_forced_support_size": order - (2 if order % 2 == 0 else 1),
            }
        )
    checks.append(
        {
            "name": "translation_quotient_remains_exponential",
            "passed": periodic_rows[0][
                "termwise_support_count_including_empty"
            ]
            == str(1 << 26)
            and periodic_rows[0]["support_orbit_lower_bound_including_empty"]
            == "2485514"
            and periodic_rows[0]["nontrivial_correlator_orbit_lower_bound"]
            == "2485514"
            and all(
                int(row["nontrivial_correlator_orbit_lower_bound"])
                * row["translation_group_order"]
                >= int(row["nontrivial_correlator_support_count"])
                for row in periodic_rows
            ),
            "detail": "after removing the known empty-support normalization, every remaining translation orbit has at most |V| supports",
        }
    )
    checks.append(
        {
            "name": "benchmark_not_used",
            "passed": True,
            "detail": "the closure theorem is combinatorial and uses only 0<v=tanh(K)<1",
        }
    )

    elapsed = time.process_time() - started
    peak_rss = peak_rss_bytes()
    checks.append(
        {
            "name": "declared_resource_limits",
            "passed": elapsed < CPU_BUDGET_SECONDS and peak_rss < RSS_LIMIT_BYTES,
            "detail": (
                f"process CPU={elapsed:.6f}s/{CPU_BUDGET_SECONDS}s; "
                f"peak RSS={peak_rss}/{RSS_LIMIT_BYTES} bytes"
            ),
        }
    )
    failed = [str(check["name"]) for check in checks if not check["passed"]]
    if failed:
        raise AssertionError(f"Callen termwise-closure checks failed: {failed}")

    source_paths = (Path(__file__).resolve(), VERIFIER, Path(callen.__file__).resolve())
    return {
        "meta": {
            "generated_utc": datetime.now(timezone.utc).isoformat(),
            "producer": "experiments/e243_callen_termwise_closure.py",
            "verifier": "tests/test_callen_termwise_closure.py",
            "interpreter": sys.executable,
            "arithmetic": "exact rational-function coefficients and finite support-set enumeration",
            "process_cpu_seconds": round(elapsed, 6),
            "process_cpu_budget_seconds": CPU_BUDGET_SECONDS,
            "peak_rss_bytes": peak_rss,
            "rss_limit_bytes": RSS_LIMIT_BYTES,
            "benchmark_Kc_used": False,
            "source_sha256": {
                str(path.relative_to(ROOT)): file_sha256(path) for path in source_paths
            },
        },
        "data": {
            "claim_tag": "[THEOREM][TERM-WISE CLOSURE NO-GO]",
            "Callen_coefficients": {
                "parameter": "v=tanh(K), 0<v<1",
                "c1": coefficients[1].as_json(),
                "c3": coefficients[3].as_json(),
                "sign_certificate": {
                    "c1": "positive: v times a polynomial with positive coefficients divided by a polynomial with positive coefficients",
                    "c3": "negative: -2*v^3 divided by a polynomial with positive coefficients",
                },
                "c5_not_used": True,
            },
            "closure_definition": (
                "the all-pivot {1,3}-termwise closure: the smallest support family containing one "
                "two-element set and, for every A in the family, every pivot x in A, and every "
                "S subset N(x) with |S|=1 or 3, also containing (A\\{x}) symmetric_difference S"
            ),
            "proof": {
                "upper_containment": "every move preserves even parity and its target omits the pivot x, so the full vertex set is never generated",
                "fixed_size_connectivity": "the size-preserving singleton moves S={y} with y outside A are exactly k-token-graph edges; connectedness of G connects all k-subsets, while occupied-neighbour moves lower size by two",
                "growth": "after all k-subsets are present, choose a vertex and three neighbours excluded from a k-set containing that vertex; the |S|=3 move produces one (k+2)-set, then token connectivity produces all of them",
                "base_and_endpoint": "all pairs imply the empty set through an occupied-neighbour edge move; induction stops at n-2 for even n and n-1 for odd n",
            },
            "finite_audits": finite_audits,
            "periodic_3x3x3": {
                "token_component_sizes": token_counts,
                "token_component_expected": expected_token_counts,
                "induction_witnesses": witnesses,
            },
            "periodic_cubic_rows": periodic_rows,
            "theorem": {
                "tag": "[THEOREM]",
                "statement": (
                    "Let G be a finite connected six-regular simple graph with n vertices in the "
                    "uniform zero-field nearest-neighbour Ising model. For every 0<v=tanh(K)<1, "
                    "the all-pivot {1,3}-termwise Callen support family generated by one two-point "
                    "correlator is exactly all even proper subsets of V(G). Its size including the "
                    "empty normalization is 2^(n-1)-1 for even n and 2^(n-1) for odd n."
                ),
                "periodic_cubic_corollary": (
                    "For C_LxC_MxC_N with L,M,N>=3 and n=LMN, the all-pivot closure has at least "
                    "ceil((2^(n-1)-[n even]-1)/n) nontrivial translation orbits after removing "
                    "the known empty-support normalization."
                ),
                "scope": "all-pivot {1,3}-termwise support closure using nonzero c1 and c3 Callen summands in the uniform zero-field nearest-neighbour model",
                "not_proved": [
                    "no-go for schemes retaining only a selected subset of pivot rows",
                    "no-go for arbitrary linear combinations of Callen rows",
                    "no-go for transforms that aggregate distinct support orbits",
                    "no-go for nonlinear, auxiliary, or nonlocal compressed variables",
                    "an exact thermodynamic solution or critical coupling",
                ],
            },
        },
        "checks": checks,
    }


def main() -> int:
    payload = run()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(payload, indent=2) + "\n")
    for check in payload["checks"]:
        print(f"  [{'PASS' if check['passed'] else 'FAIL'}] {check['name']}: {check['detail']}")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
