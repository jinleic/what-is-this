"""THE decisive algebraic experiment for Track A.

The layer-to-layer transfer operator of the (d+1)-dimensional classical Ising model is

    V = exp(K* A) exp(K B),     A = sum_i X_i,     B = sum_{<ij> in layer} Z_i Z_j .

Only the Lie algebra generated by the TWO elements A and B matters for diagonalising V.  In one
dimension this is the Onsager algebra, and its finite dimension is exactly why Onsager could solve
the 2D Ising model without ever invoking free fermions.  This script measures

    dim <A, B>_Lie

exactly, for 1D layers (2D Ising) and 2D layers (3D Ising).

Arithmetic: exact over F_p with two different 31-bit primes; the reported dimension is a rigorous
lower bound on the rank over Q and coincides with it unless BOTH primes divide a minor.
"""

from __future__ import annotations

import json
import time

from ising.clifford import pauli_x, zz
from ising.clifford.fast_lie import GeneratedAlgebra, P1, P2


def grid(a, b, per_a=False, per_b=False):
    n = a * b
    idx = lambda x, y: x * b + y  # noqa: E731
    bonds = []
    for x in range(a):
        for y in range(b):
            if x + 1 < a:
                bonds.append((idx(x, y), idx(x + 1, y)))
            elif per_a and a > 2:
                bonds.append((idx(x, y), idx(0, y)))
            if y + 1 < b:
                bonds.append((idx(x, y), idx(x, y + 1)))
            elif per_b and b > 2:
                bonds.append((idx(x, y), idx(x, 0)))
    return list(range(n)), bonds, n


def onsager_dim(a, b, per_a=False, per_b=False, p=P1, max_dim=None, report=None):
    sites, bonds, n = grid(a, b, per_a, per_b)
    xs = [pauli_x(n, i) for i in sites]
    zs = [zz(n, i, j) for i, j in bonds]
    singles = xs + zs
    A = {g: 1 for g in xs}
    B = {g: 1 for g in zs}
    alg = GeneratedAlgebra([A, B], singles, n, p=p)
    gA = list(range(len(xs)))
    gB = list(range(len(xs), len(singles)))
    d = alg.closure_dim([A, B], [gA, gB], max_dim=max_dim, report=report)
    return d, alg.m, n, len(bonds)


if __name__ == "__main__":
    out = []
    print("=== 1D layers (2D classical Ising): <A,B> = ONSAGER ALGEBRA ===", flush=True)
    for L in range(2, 15):
        t0 = time.time()
        d, m, n, nb = onsager_dim(1, L)
        print(f"  open chain n={L:2d}: dim<A,B> = {d:6d}   n^2 = {n*n:6d}   support {m:8d}   {time.time()-t0:5.1f}s", flush=True)
        out.append(dict(kind="chain_open", n=L, dim=d, support=m, bonds=nb))
    for L in range(3, 13):
        d, m, n, nb = onsager_dim(1, L, per_b=True)
        print(f"  ring       n={L:2d}: dim<A,B> = {d:6d}   3n-1 = {3*n-1:6d}   support {m:8d}", flush=True)
        out.append(dict(kind="chain_periodic", n=L, dim=d, support=m, bonds=nb))

    print("=== 2D layers (3D classical Ising) ===", flush=True)
    for (a, b) in [(2, 2), (2, 3), (2, 4)]:
        t0 = time.time()
        try:
            d, m, n, nb = onsager_dim(a, b, max_dim=250000)
            print(f"  grid {a}x{b} (n={n:2d}): dim<A,B> = {d:8d}   support {m:9d}   4^(n-1) = {4**(n-1):10d}   {time.time()-t0:7.1f}s", flush=True)
            out.append(dict(kind="grid_open", a=a, b=b, n=n, dim=d, support=m, bonds=nb))
        except (MemoryError, AssertionError) as e:
            print(f"  grid {a}x{b}: ABORTED -- {type(e).__name__}: {e}", flush=True)
            out.append(dict(kind="grid_open", a=a, b=b, dim=None, note=f"{type(e).__name__}: {e}"))

    print("=== second prime certification ===", flush=True)
    for (a, b) in [(1, 6), (1, 8), (2, 3), (2, 4)]:
        d1, _, _, _ = onsager_dim(a, b, p=P1)
        d2, _, _, _ = onsager_dim(a, b, p=P2)
        print(f"  {a}x{b}: p1 -> {d1}, p2 -> {d2}  {'AGREE' if d1 == d2 else 'DISAGREE'}", flush=True)
        out.append(dict(kind="prime_check", a=a, b=b, p1=d1, p2=d2, agree=d1 == d2))

    json.dump(out, open("results/onsager_algebra_dims.json", "w"), indent=1)
    print("written results/onsager_algebra_dims.json")
