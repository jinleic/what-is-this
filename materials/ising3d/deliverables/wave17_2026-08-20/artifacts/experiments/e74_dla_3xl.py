"""Exact finite certificates and an induction obstruction for the open 3xL DLA.

For the open three-row grid, this script studies the Lie algebra generated by
A=sum X_v and B=sum_{uv in E} Z_u Z_v.  It records exact/modular depth data,
an explicit binary family of integer Lie words, nonzero integer minors, and an
exhaustive obstruction to a natural product-lex leading-term induction.

The result is deliberately finite.  A nonzero modular minor is a lower bound
on rational rank; neither prime agreement nor a finite size pattern is used as
an upper bound or promoted to an all-L theorem.
"""

