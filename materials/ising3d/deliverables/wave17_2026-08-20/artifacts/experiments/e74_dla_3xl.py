def archived_profiles() -> list[dict[str, object]]:
    path = ROOT / "results" / "algebra_growth" / "profiles.json"
    artifact = json.loads(path.read_text(encoding="utf-8"))
    selected: dict[tuple[int, int], dict[str, object]] = {}
    for record in artifact["data"]["profiles"]:
        key = (int(record["rows"]), int(record["cols"]))
        if key in ((3, 2), (3, 3), (3, 4)) and int(record["prime"]) == P1:
            selected[key] = record
    if (3, 2) not in selected:
        # The archived e20 file stores the congruent orientation as grid_2x3.
        for record in artifact["data"]["profiles"]:
            if (
                int(record["rows"]), int(record["cols"]), int(record["prime"])
            ) == (2, 3, P1):
                selected[(3, 2)] = record
                break
    result = []
    for shape in ((3, 2), (3, 3), (3, 4)):
        record = selected[shape]
        result.append(
            {
                "shape": list(shape),
                "source_case": record["case"],
                "prime": P1,
                "dimensions": record["dimensions"],
                "completed_depth": record["completed_depth"],
                "saturated": record["saturated"],
                "modular_dimension": record["exact_dimension"],
                "lower_bound_Q": record["lower_bound"],
                "stop_reason": record["stop_reason"],
                "scope": (
                    "complete modular closure; gives a Q lower bound only"
                    if record["saturated"]
                    else "complete depths only; final value is a Q lower bound, not a dimension equality"
                ),
            }
        )
    # Wave 8 extended the 3x4 prefix by one complete sparse depth.  The
    # measurement is frozen in this artifact because recomputing it costs
    # several minutes; the standalone test treats it only as a claimed
    # finite lower-bound record and never as a dimension equality.
    wave8_profile = EXPECTED_PROFILES[(3, 4)]
    if result[-1]["dimensions"] != wave8_profile[:-1]:
        raise AssertionError("archived 3x4 prefix no longer matches the measured depth-15 extension")
    result[-1].update(
        {
            "dimensions": wave8_profile,
            "completed_depth": 15,
            "lower_bound_Q": 1242,
            "stop_reason": "max_depth=15",
            "wave8_extension": {
                "engine": "e20 sparse orbit engine",
                "prime": P1,
                "command": (
                    ".venv/bin/python -c \"from experiments.e20_algebra_growth import "
                    "compute_profile; print(compute_profile(3,4,max_depth=15,"
                    "prime=2147483647,engine='sparse',memory_limit_bytes=4000000000))\""
                ),
                "basis_used_bytes": 773_276_448,
                "rss_peak_bytes": 989_380_608,
                "elapsed_seconds": "456.747006",
                "measured_utc_date": "2026-08-13",
            },
            "scope": "depths 1..15 complete modulo p; 1242 is a rigorous Q lower bound, not the full DLA dimension",
        }
    )
    return result


def family_record(length: int, include_minor: bool) -> dict[str, object]:
    words = recursive_words(length)
    vectors = [word_vector(word, length) for _, word in words]
    ranks = {str(prime): rank_mod(vectors, prime) for prime in PRIMES}
    rows = [
        {
            "label": label,
            "subset_columns": [
                column + 1 for column, bit in enumerate(label) if bit == "1"
            ],
            "word": word,
            "depth": len(word),
            "support_size": len(vector),
            "sha256": vector_digest(vector),
        }
        for (label, word), vector in zip(words, vectors)
    ]
    result: dict[str, object] = {
        "length": length,
        "count": len(words),
        "maximum_depth": max(len(word) for _, word in words),
        "rank_mod": ranks,
        "rows": rows,
    }
    if include_minor:
        columns = pivot_columns(vectors, P1)
        matrix = [[vector.get(column, 0) for column in columns] for vector in vectors]
        determinant = determinant_bareiss(matrix)
        result["integer_minor"] = {
            "size": len(columns),
            "pauli_columns": columns,
            "pauli_strings": [pauli_string(column, length) for column in columns],
            "determinant_Z": str(determinant),
            "determinant_mod": {str(prime): determinant % prime for prime in PRIMES},
            "nonzero_over_Q": determinant != 0,
            "selection": f"first-pivot columns under sparse elimination modulo {P1}",
        }
    return result


