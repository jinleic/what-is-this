def grid_bonds(length: int) -> tuple[int, tuple[tuple[int, int], ...]]:
    """Open 3xL grid in row-major site order."""

    if length < 2:
        raise ValueError("length must be at least two")
    rows = 3
    n = rows * length
    bonds: list[tuple[int, int]] = []
    for row in range(rows):
        for col in range(length):
            site = row * length + col
            if row + 1 < rows:
                bonds.append((site, site + length))
            if col + 1 < length:
                bonds.append((site, site + 1))
    return n, tuple(bonds)


def generator_terms(length: int) -> tuple[tuple[int, ...], tuple[int, ...]]:
    n, bonds = grid_bonds(length)
    a_terms = tuple(1 << site for site in range(n))
    b_terms = tuple((1 << (n + lhs)) | (1 << (n + rhs)) for lhs, rhs in bonds)
    return a_terms, b_terms


def sign_half(left: int, right: int, n: int) -> int:
    """Coefficient of Q_(left xor right) in [Q_left,Q_right]/2."""

    mask = (1 << n) - 1
    lr = (((left >> n) & mask) & (right & mask)).bit_count() & 1
    rl = (((right >> n) & mask) & (left & mask)).bit_count() & 1
    if lr == rl:
        return 0
    return 1 if lr == 0 else -1


def adjoint(terms: Sequence[int], vector: Vector, n: int) -> Vector:
    result: Vector = {}
    for term in terms:
        for pauli, coefficient in vector.items():
            sign = sign_half(term, pauli, n)
            if sign:
                target = term ^ pauli
                value = result.get(target, 0) + sign * coefficient
                if value:
                    result[target] = value
                else:
                    result.pop(target, None)
    return result


def word_vector(word: str, length: int) -> Vector:
    """Evaluate an outermost-first left-nested A/B word over exact integers."""

    if not word or any(letter not in "AB" for letter in word):
        raise ValueError("word must be a nonempty A/B string")
    n = 3 * length
    a_terms, b_terms = generator_terms(length)
    terms = {"A": a_terms, "B": b_terms}
    value = {term: 1 for term in terms[word[-1]]}
    for letter in reversed(word[:-1]):
        value = adjoint(terms[letter], value, n)
    return value


def recursive_words(length: int) -> list[tuple[str, str]]:
    """The tested binary family; every word has depth at most 2L."""

    if length < 2:
        raise ValueError("length must be at least two")
    family = [("00", "A"), ("01", "BA"), ("10", "ABA"), ("11", "BABA")]
    for _ in range(2, length):
        family = [
            child
            for label, word in family
            for child in ((label + "0", "AB" + word), (label + "1", "BB" + word))
        ]
    return family


def rank_mod(rows: Sequence[Vector], prime: int) -> int:
    pivots: dict[int, Vector] = {}
    for row in rows:
        value = {key: coefficient % prime for key, coefficient in row.items() if coefficient % prime}
        while value:
            lead = min(value)
            existing = pivots.get(lead)
            if existing is None:
                inverse = pow(value[lead], prime - 2, prime)
                value = {
                    key: coefficient * inverse % prime
                    for key, coefficient in value.items()
                    if coefficient * inverse % prime
                }
                pivots[lead] = value
                break
            factor = value[lead]
            for key, coefficient in existing.items():
                reduced = (value.get(key, 0) - factor * coefficient) % prime
                if reduced:
                    value[key] = reduced
                else:
                    value.pop(key, None)
    return len(pivots)


def pivot_columns(rows: Sequence[Vector], prime: int) -> list[int]:
    """Return explicit original Pauli columns giving a full-rank row minor."""

    pivots: dict[int, Vector] = {}
    columns: list[int] = []
    for row in rows:
        value = {key: coefficient % prime for key, coefficient in row.items() if coefficient % prime}
        while value:
            lead = min(value)
            existing = pivots.get(lead)
            if existing is None:
                inverse = pow(value[lead], prime - 2, prime)
                value = {
                    key: coefficient * inverse % prime
                    for key, coefficient in value.items()
                    if coefficient * inverse % prime
                }
                pivots[lead] = value
                columns.append(lead)
                break
            factor = value[lead]
            for key, coefficient in existing.items():
                reduced = (value.get(key, 0) - factor * coefficient) % prime
                if reduced:
                    value[key] = reduced
                else:
                    value.pop(key, None)
    return columns


def determinant_bareiss(matrix: Sequence[Sequence[int]]) -> int:
    """Fraction-free exact determinant over Z."""

    data = [list(map(int, row)) for row in matrix]
    n = len(data)
    if any(len(row) != n for row in data):
        raise ValueError("determinant requires a square matrix")
    if n == 0:
        return 1
    sign = 1
    denominator = 1
    for column in range(n - 1):
        if data[column][column] == 0:
            swap = next((row for row in range(column + 1, n) if data[row][column]), None)
            if swap is None:
                return 0
            data[column], data[swap] = data[swap], data[column]
            sign = -sign
        pivot = data[column][column]
        for row in range(column + 1, n):
            for other in range(column + 1, n):
                numerator = data[row][other] * pivot - data[row][column] * data[column][other]
                data[row][other] = numerator // denominator
            data[row][column] = 0
        denominator = pivot
    return sign * data[-1][-1]


def vector_digest(vector: Vector) -> str:
    digest = hashlib.sha256()
    for pauli, coefficient in sorted(vector.items()):
        digest.update(f"{pauli}:{coefficient};".encode("ascii"))
    return digest.hexdigest()


def pauli_string(pauli: int, length: int) -> str:
    n = 3 * length
    mask = (1 << n) - 1
    a, b = pauli & mask, (pauli >> n) & mask
    return " ".join(
        "".join(
            BITS_TO_LABEL[((a >> (row * length + col)) & 1, (b >> (row * length + col)) & 1)]
            for row in range(3)
        )
        for col in range(length)
    )


def monomial_key(
    pauli: int,
    length: int,
    rung_reverse: bool,
    row_reverse: bool,
    ascending_local_order: str,
) -> tuple[int, ...]:
    n = 3 * length
    mask = (1 << n) - 1
    a, b = pauli & mask, (pauli >> n) & mask
    rank = {letter: index for index, letter in enumerate(ascending_local_order)}
    columns: Iterable[int] = range(length - 1, -1, -1) if rung_reverse else range(length)
    rows: Iterable[int] = range(2, -1, -1) if row_reverse else range(3)
    return tuple(
        rank[BITS_TO_LABEL[((a >> (row * length + col)) & 1, (b >> (row * length + col)) & 1)]]
        for col in columns
        for row in rows
    )


def product_lex_scan(vectors: Sequence[Vector], length: int) -> dict[str, object]:
    histogram: dict[int, int] = {}
    maximum = 0
    maximizers: list[dict[str, object]] = []
    for rung_reverse, row_reverse, order_tuple in itertools.product(
        (False, True), (False, True), itertools.permutations(LABELS)
    ):
        order = "".join(order_tuple)
        leaders = {
            max(
                vector,
                key=lambda pauli: monomial_key(
                    pauli, length, rung_reverse, row_reverse, order
                ),
            )
            for vector in vectors
        }
        count = len(leaders)
        histogram[count] = histogram.get(count, 0) + 1
        if count > maximum:
            maximum = count
            maximizers = []
        if count == maximum:
            maximizers.append(
                {
                    "rung_reverse": rung_reverse,
                    "row_reverse": row_reverse,
                    "ascending_local_order": order,
                }
            )
    return {
        "orders_tested": 96,
        "histogram": {str(key): histogram[key] for key in sorted(histogram)},
        "maximum_distinct_raw_leaders": maximum,
        "required": len(vectors),
        "maximizers": maximizers,
    }


def _load_e20():
    path = ROOT / "experiments" / "e20_algebra_growth.py"
    spec = importlib.util.spec_from_file_location("e20_for_e74", path)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load e20 algebra-growth engine")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def recompute_three_by_two_profiles() -> list[dict[str, object]]:
    e20 = _load_e20()
    records = []
    for prime in PRIMES:
        profile = e20.compute_profile(3, 2, prime=prime, engine="dense")
        records.append(
            {
                "shape": [3, 2],
                "prime": prime,
                "dimensions": profile["dimensions"],
                "saturated": profile["saturated"],
                "modular_dimension": profile["exact_dimension"],
                "support_orbits": profile["support_orbits"],
                "point_group_order": profile["point_group_order"],
                "grading_block_columns": profile["grading_block_columns"],
                "grading_block_rows": profile["grading_block_rows"],
            }
        )
    return records


