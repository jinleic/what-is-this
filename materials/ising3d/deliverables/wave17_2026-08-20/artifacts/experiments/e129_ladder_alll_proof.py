class LadderStates:
    """Hard-core bosons on the 2xL ladder, computational basis = X eigenbasis."""

    def __init__(self, L: int, p: int = P1):
        self.L = L
        self.n = 2 * L
        self.p = p
        self.N = 1 << self.n
        self.edges = ladder_edges(L)
        idx = np.arange(self.N, dtype=np.int64)
        ity = np.int32 if self.N < (1 << 31) else np.int64
        # For each edge store the destination index set and the matching source
        # index set of each of the three moves, so that an application is a pure
        # gather/scatter with no per-call index arithmetic.
        self._sel: list[tuple] = []
        for (u, v) in self.edges:
            bu = (idx >> u) & 1
            bv = (idx >> v) & 1
            m = (1 << u) | (1 << v)
            both1 = np.flatnonzero((bu == 1) & (bv == 1)).astype(ity)
            both0 = np.flatnonzero((bu == 0) & (bv == 0)).astype(ity)
            mixed = np.flatnonzero(bu != bv).astype(ity)
            self._sel.append((both1, (both1 ^ ity(m)), both0, (both0 ^ ity(m)),
                              mixed, (mixed ^ ity(m))))
        self.popc = np.zeros(self.N, dtype=np.int8)
        for b in range(self.n):
            self.popc += ((idx >> b) & 1).astype(np.int8)
        del idx

    def zero(self) -> np.ndarray:
        return np.zeros(self.N, dtype=np.int64)

    def vacuum(self) -> np.ndarray:
        v = self.zero()
        v[0] = 1
        return v

    def apply_D(self, vec: np.ndarray) -> np.ndarray:
        out = self.zero()
        for dst, src, _d0, _s0, _dm, _sm in self._sel:
            out[dst] += vec[src]
        return out % self.p

    def apply_Dd(self, vec: np.ndarray) -> np.ndarray:
        out = self.zero()
        for _d1, _s1, dst, src, _dm, _sm in self._sel:
            out[dst] += vec[src]
        return out % self.p

    def apply_F(self, vec: np.ndarray) -> np.ndarray:
        out = self.zero()
        for _d1, _s1, _d0, _s0, dst, src in self._sel:
            out[dst] += vec[src]
        return out % self.p

    def apply_B(self, vec: np.ndarray) -> np.ndarray:
        return (self.apply_D(vec) + self.apply_F(vec) + self.apply_Dd(vec)) % self.p

    def apply_A(self, vec: np.ndarray) -> np.ndarray:
        return ((self.n - 2 * self.popc.astype(np.int64)) * vec) % self.p

    def op(self, letter: str):
        return {"D": self.apply_D, "F": self.apply_F, "d": self.apply_Dd}[letter]


DELTA_N = {"D": 2, "F": 0, "d": -2}


def apply_lie_word(S: LadderStates, word: str, vec: np.ndarray) -> np.ndarray:
    """word = g1 g2 ... gk  ->  [g1,[g2,[...,[g_{k-1}, g_k]...]]] applied to vec."""
    if len(word) == 1:
        return S.op(word)(vec)
    g = S.op(word[0])
    a = g(apply_lie_word(S, word[1:], vec))
    b = apply_lie_word(S, word[1:], g(vec))
    return (a - b) % S.p


class ProjEchelon:
    """Row echelon over F_p of vectors projected by a signed fold to width M."""

    def __init__(self, S: LadderStates, width: int, seed: int):
        self.p = S.p
        rng = np.random.default_rng(seed)
        self.width = min(width, S.N)
        # width must divide S.N so that the fold is a clean reshape
        w = 1
        while w * 2 <= self.width:
            w *= 2
        self.width = w
        self.signs = rng.integers(0, 2, size=S.N, dtype=np.int64) * 2 - 1
        self.folds = S.N // self.width
        self.rows: dict[int, np.ndarray] = {}

    def project(self, vec: np.ndarray) -> np.ndarray:
        return ((vec * self.signs).reshape(self.folds, self.width).sum(axis=0)) % self.p

    def add_projected(self, r: np.ndarray) -> bool:
        p = self.p
        r = r % p
        while True:
            nz = np.flatnonzero(r)
            if nz.size == 0:
                return False
            piv = int(nz[-1])
            if piv not in self.rows:
                inv = pow(int(r[piv]), p - 2, p)
                self.rows[piv] = (r * inv) % p
                return True
            r = (r - int(r[piv]) * self.rows[piv]) % p

    def add(self, vec: np.ndarray) -> bool:
        return self.add_projected(self.project(vec))

    def __len__(self) -> int:
        return len(self.rows)

class ResidueEchelon:
    """Exact row echelon over F_p for already-projected vectors."""

    def __init__(self, p: int):
        self.p = p
        self.rows: dict[int, np.ndarray] = {}

    def add(self, r: np.ndarray) -> bool:
        r = r % self.p
        while True:
            nz = np.flatnonzero(r)
            if nz.size == 0:
                return False
            piv = int(nz[-1])
            if piv not in self.rows:
                self.rows[piv] = (r * pow(int(r[piv]), self.p - 2, self.p)) % self.p
                return True
            r = (r - int(r[piv]) * self.rows[piv]) % self.p

    def __len__(self) -> int:
        return len(self.rows)

class RungLexLeaderTracker:
    """Triangular independence screen in (particle number, rung-lex) order."""

    def __init__(self, S: LadderStates):
        idx = np.arange(S.N, dtype=np.int64)
        rung_lex = np.zeros(S.N, dtype=np.int64)
        for i in range(S.L):
            rung = (idx >> (2 * i)) & 3
            rung_lex |= rung << (2 * (S.L - 1 - i))
        order = np.lexsort((rung_lex, S.popc))
        self.order_rank = np.empty(S.N, dtype=np.int64)
        self.order_rank[order] = np.arange(S.N, dtype=np.int64)
        self.seen_leaders: set[int] = set()
        self.candidate_vectors_seen = 0

    def add(self, vec: np.ndarray) -> bool:
        self.candidate_vectors_seen += 1
        nz = np.flatnonzero(vec)
        if nz.size == 0:
            return False
        leader = int(nz[np.argmin(self.order_rank[nz])])
        if leader in self.seen_leaders:
            return False
        self.seen_leaders.add(leader)
        return True

    def summary(self) -> dict:
        return {
            "order": "(particle_number, rung_adapted_lexicographic)",
            "candidate_vectors_seen": self.candidate_vectors_seen,
            "distinct_minimum_support_leaders": len(self.seen_leaders),
        }


