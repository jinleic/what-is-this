def ceiling_dim(L: int) -> dict:
    """dim of the <tau,rho>-invariant even-particle-number subspace, in closed form.

    tau  : swap the two legs.       rho : reverse the rungs.
    Every element of g_L is fixed by both, and g_L preserves particle parity,
    so g_L.psi lies in K_L.
    """
    n = 2 * L
    total_even = 1 << (n - 1)
    fix_tau = 1 << L                      # x_{t_i} = x_{b_i}; parity automatic
    if L % 2 == 0:
        fix_rho = 1 << L                  # L/2 free rung pairs, 2 rows: 2^(2*(L/2))
    else:
        # (L-1)/2 free pairs per row plus a free middle rung, even parity forces
        # the middle rung to have even occupancy: 2 of its 4 states.
        fix_rho = (1 << (L - 1)) * 2
    fix_taurho = 1 << L                   # x_{t_i} = x_{b_{L+1-i}}; parity automatic
    dim = (total_even + fix_tau + fix_rho + fix_taurho) // 4
    return {
        "L": L,
        "even_configs": total_even,
        "fix_tau": fix_tau,
        "fix_rho": fix_rho,
        "fix_taurho": fix_taurho,
        "dim_K": dim,
        "lower_bound_2_2L_minus_3": 1 << (2 * L - 3),
    }


def ceiling_direct_invariant_basis(L: int) -> tuple[int, dict[str, int]]:
    """Count the disjoint <tau,rho>-orbit-sum basis, sector by sector."""
    n = 2 * L

    def tau(x: int) -> int:
        y = 0
        for i in range(L):
            y |= ((x >> (2 * i + 1)) & 1) << (2 * i)
            y |= ((x >> (2 * i)) & 1) << (2 * i + 1)
        return y

    def rho(x: int) -> int:
        y = 0
        for i in range(L):
            j = L - 1 - i
            y |= ((x >> (2 * i)) & 1) << (2 * j)
            y |= ((x >> (2 * i + 1)) & 1) << (2 * j + 1)
        return y

    seen: set[int] = set()
    sector_dims: dict[str, int] = {}
    for x in range(1 << n):
        weight = x.bit_count()
        if weight & 1 or x in seen:
            continue
        orbit = {x, tau(x), rho(x), tau(rho(x))}
        if any(y.bit_count() != weight for y in orbit):
            raise AssertionError("ladder symmetry changed particle number")
        seen |= orbit
        sector_dims[str(weight)] = sector_dims.get(str(weight), 0) + 1
    return sum(sector_dims.values()), sector_dims


def ceiling_dim_bruteforce(L: int) -> int:
    return ceiling_direct_invariant_basis(L)[0]


