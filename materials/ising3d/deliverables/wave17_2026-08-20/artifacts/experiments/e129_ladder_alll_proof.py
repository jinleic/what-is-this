def krylov_profile(L: int, max_sector: int | None = None) -> dict:
    """Exact F_p Krylov ranks of selected seeds inside the invariant sectors."""
    S = LadderStates(L)
    psi = S.vacuum()
    _, invariant_sector_dims = ceiling_direct_invariant_basis(L)
    prof = {}
    for m in range(1, (L if max_sector is None else min(L, max_sector)) + 1):
        particle_number = 2 * m
        word = "D" * m + "F"
        v = apply_lie_word(S, word, psi)
        target = invariant_sector_dims[str(particle_number)]
        full_sector = int(np.count_nonzero(S.popc == particle_number))
        if not v.any():
            prof[str(particle_number)] = {
                "seed_word": word,
                "seed_nonzero": False,
                "F_krylov_rank_mod_p1": 0,
                "invariant_sector_dim_K": target,
                "full_particle_sector_dim": full_sector,
                "selected_seed_is_F_cyclic_in_K": False,
            }
            continue
        ech = ProjEchelon(S, S.N, seed=13)
        cur = v.copy()
        dim = 0
        while ech.add(cur):
            dim += 1
            cur = S.apply_F(cur)
            if not cur.any() or dim > 4000:
                break
        prof[str(particle_number)] = {
            "seed_word": word,
            "seed_nonzero": True,
            "F_krylov_rank_mod_p1": dim,
            "invariant_sector_dim_K": target,
            "full_particle_sector_dim": full_sector,
            "selected_seed_is_F_cyclic_in_K": dim == target,
        }
    return prof


