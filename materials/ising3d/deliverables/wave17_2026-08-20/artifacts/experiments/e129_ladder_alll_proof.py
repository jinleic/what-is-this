def ladder_edges(L: int) -> list[tuple[int, int]]:
    """Site 2i = top of rung i, site 2i+1 = bottom of rung i (0-based rungs)."""
    edges = [(2 * i, 2 * i + 1) for i in range(L)]
    for i in range(L - 1):
        edges.append((2 * i, 2 * i + 2))
        edges.append((2 * i + 1, 2 * i + 3))
    return edges


