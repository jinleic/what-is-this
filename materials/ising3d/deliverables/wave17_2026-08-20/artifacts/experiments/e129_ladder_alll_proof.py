def pauli_half_bracket(n: int, p: int, q: int) -> tuple[int, int] | None:
    """(1/2)[Q_p, Q_q] with Q_(a|b) = X^a Z^b; returns (code, sign) or None."""
    mask = (1 << n) - 1
    ap, bp = p & mask, p >> n
    aq, bq = q & mask, q >> n
    s1 = bin(bp & aq).count("1") & 1
    s2 = bin(bq & ap).count("1") & 1
    if s1 == s2:
        return None
    return p ^ q, (1 if s1 == 0 else -1)


def pauli_bracket(n: int, u: dict[int, Fraction], v: dict[int, Fraction]) -> dict[int, Fraction]:
    """[u, v] (not halved) in the integer Pauli basis."""
    out: dict[int, Fraction] = {}
    for p, cp in u.items():
        for q, cq in v.items():
            r = pauli_half_bracket(n, p, q)
            if r is None:
                continue
            code, sign = r
            val = out.get(code, Fraction(0)) + 2 * sign * cp * cq
            if val:
                out[code] = val
            else:
                out.pop(code, None)
    return out


def pauli_lincomb(*pairs) -> dict[int, Fraction]:
    out: dict[int, Fraction] = {}
    for coef, vec in pairs:
        for k, c in vec.items():
            val = out.get(k, Fraction(0)) + coef * c
            if val:
                out[k] = val
            else:
                out.pop(k, None)
    return out


def structure_identity_check(L: int) -> dict:
    """Verify B = D + F + Ddag and the three ad_A eigencomponent formulas exactly."""
    n = 2 * L
    edges = ladder_edges(L)
    A = {1 << v: Fraction(1) for v in range(n)}                     # X^a, a = e_v
    B = {((1 << u) | (1 << v)) << n: Fraction(1) for (u, v) in edges}

    # D / F / Ddag written in the Pauli basis.
    # Z_u Z_v flips sites u and v in the X-eigenbasis; the pieces are selected by
    # the projectors onto the four (X_u, X_v) sign patterns:
    #   D   : both sites |+>   -> P^+_u P^+_v Z_u Z_v
    #   Ddag: both sites |->   -> P^-_u P^-_v Z_u Z_v
    #   F   : mixed            -> (P^+_u P^-_v + P^-_u P^+_v) Z_u Z_v
    # with P^pm_v = (1 pm X_v)/2.
    def proj_terms(u: int, su: int, v: int, sv: int) -> dict[int, Fraction]:
        """(1 + su X_u)/2 * (1 + sv X_v)/2 as a Pauli dict (X-part only)."""
        out = {}
        for cu, ku in ((Fraction(1, 2), 0), (Fraction(su, 2), 1 << u)):
            for cv, kv in ((Fraction(1, 2), 0), (Fraction(sv, 2), 1 << v)):
                key = ku | kv
                out[key] = out.get(key, Fraction(0)) + cu * cv
        return {k: c for k, c in out.items() if c}

    def piece(sel) -> dict[int, Fraction]:
        acc: dict[int, Fraction] = {}
        for (u, v) in edges:
            zz = ((1 << u) | (1 << v)) << n
            for (su, sv) in sel:
                pr = proj_terms(u, su, v, sv)
                for k, c in pr.items():
                    # X^k * Z^{e_u+e_v} : X and Z parts live in disjoint halves,
                    # the product Q_(k|0) Q_(0|zz) = Q_(k|zz) with sign +1.
                    key = k | zz
                    acc[key] = acc.get(key, Fraction(0)) + c
        return {k: c for k, c in acc.items() if c}

    # ORDERING: Q_(a|b) = X^a Z^b acts as "Z^b first, then X^a", so the
    # projector carried by the X-part constrains the OUTPUT configuration.
    # Pair creation maps both-empty to both-occupied, i.e. output projector
    # P^-_u P^-_v; pair annihilation is the mirror case.
    D = piece([(-1, -1)])
    Dd = piece([(+1, +1)])
    F = piece([(+1, -1), (-1, +1)])

    checks = {}
    checks["B_eq_D_F_Ddag"] = pauli_lincomb((1, B), (-1, D), (-1, F), (-1, Dd)) == {}
    adAB = pauli_bracket(n, A, B)
    adAAB = pauli_bracket(n, A, adAB)
    checks["D_formula"] = pauli_lincomb(
        (Fraction(1, 32), adAAB), (Fraction(-1, 8), adAB), (-1, D)
    ) == {}
    checks["Ddag_formula"] = pauli_lincomb(
        (Fraction(1, 32), adAAB), (Fraction(1, 8), adAB), (-1, Dd)
    ) == {}
    checks["F_formula"] = pauli_lincomb(
        (1, B), (Fraction(-1, 16), adAAB), (-1, F)
    ) == {}
    # ad_A eigenvalues
    checks["adA_D_eq_minus4D"] = pauli_lincomb((1, pauli_bracket(n, A, D)), (4, D)) == {}
    checks["adA_F_eq_0"] = pauli_bracket(n, A, F) == {}
    checks["adA_Ddag_eq_plus4Ddag"] = pauli_lincomb(
        (1, pauli_bracket(n, A, Dd)), (-4, Dd)
    ) == {}
    return {"L": L, "all_passed": all(checks.values()), "checks": checks}


