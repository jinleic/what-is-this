def full_closure_dim(L: int, p: int = P1) -> tuple[int, list[dict[int, int]]]:
    n = 2 * L
    mask = (1 << n) - 1
    edges = ladder_edges(L)
    A = {1 << v: 1 for v in range(n)}
    B = {((1 << u) | (1 << v)) << n: 1 for (u, v) in edges}

    def half_bracket(u: dict[int, int], v: dict[int, int]) -> dict[int, int]:
        out: dict[int, int] = {}
        for pp, cp in u.items():
            ap, bp = pp & mask, pp >> n
            for q, cq in v.items():
                aq, bq = q & mask, q >> n
                s1 = bin(bp & aq).count("1") & 1
                s2 = bin(bq & ap).count("1") & 1
                if s1 == s2:
                    continue
                sign = 1 if s1 == 0 else -1
                key = pp ^ q
                val = (out.get(key, 0) + sign * cp * cq) % p
                if val:
                    out[key] = val
                else:
                    out.pop(key, None)
        return out

    rows: dict[int, dict[int, int]] = {}

    def add(vec: dict[int, int]) -> bool:
        v = {k: c % p for k, c in vec.items() if c % p}
        while v:
            piv = max(v)
            if piv not in rows:
                inv = pow(v[piv], p - 2, p)
                rows[piv] = {k: (c * inv) % p for k, c in v.items()}
                return True
            f = v[piv]
            for k, c in rows[piv].items():
                nv = (v.get(k, 0) - f * c) % p
                if nv:
                    v[k] = nv
                else:
                    v.pop(k, None)
        return False

    basis = []
    for g in (A, B):
        if add(g):
            basis.append(g)
    i = 0
    while i < len(basis):
        cur = basis[i]
        for g in (A, B):
            w = half_bracket(g, cur)
            if w and add(w):
                basis.append(w)
        i += 1
    return len(rows), basis


def evaluation_at_plus(L: int, basis: list[dict[int, int]], p: int = P1) -> int:
    """dim of g_L . |+>^{2L}, computed from a Pauli basis of g_L."""
    n = 2 * L
    mask = (1 << n) - 1
    rows: dict[int, dict[int, int]] = {}

    def add(vec: dict[int, int]) -> bool:
        v = {k: c % p for k, c in vec.items() if c % p}
        while v:
            piv = max(v)
            if piv not in rows:
                inv = pow(v[piv], p - 2, p)
                rows[piv] = {k: (c * inv) % p for k, c in v.items()}
                return True
            f = v[piv]
            for k, c in rows[piv].items():
                nv = (v.get(k, 0) - f * c) % p
                if nv:
                    v[k] = nv
                else:
                    v.pop(k, None)
        return False

    count = 0
    for vec in basis:
        img: dict[int, int] = {}
        for code, c in vec.items():
            a, b = code & mask, code >> n
            # In the X eigenbasis Z^b flips exactly the sites of b and X^a acts
            # by (-1)^{a.x}.  Applying X^a Z^b to x = 0 gives the basis vector b
            # with coefficient (-1)^{|a & b|}.
            sgn = -1 if (bin(a & b).count("1") & 1) else 1
            img[b] = (img.get(b, 0) + sgn * c) % p
        img = {k: c for k, c in img.items() if c}
        if img and add(img):
            count += 1
    return len(rows)

def rung_staggered_configuration(L: int) -> int:
    """Rungs 0,2,... empty and rungs 1,3,... fully occupied in the X basis."""
    return sum((3 << (2 * i)) for i in range(L) if i & 1)


def multivector_evaluation_preflight(
    L: int = 9,
    word_len: int = 4,
    projection_width_per_state: int = 1024,
    seed: int = 20260817,
    time_budget: float = 90.0,
) -> dict:
    """Cheap direct multi-state evaluation lower bound from a finite word pool."""
    t0 = time.perf_counter()
    rss_start = peak_rss_bytes()
    deadline = t0 + max(0.0, time_budget - WALL_GUARD_SECONDS)
    S = LadderStates(L)
    width = min(S.N, projection_width_per_state)
    w = 1
    while w * 2 <= width:
        w *= 2
    width = w
    folds = S.N // width
    rng = np.random.default_rng(seed)
    signs = [
        rng.integers(0, 2, size=S.N, dtype=np.int64) * 2 - 1
        for _ in range(3)
    ]

    def fold(vec: np.ndarray, sign: np.ndarray) -> np.ndarray:
        return ((vec * sign).reshape(folds, width).sum(axis=0)) % S.p

    configs = [0, S.N - 1, rung_staggered_configuration(L)]
    states = []
    for x in configs:
        vec = S.zero()
        vec[x] = 1
        states.append(vec)
    words = lie_words(word_len)
    echelon = ResidueEchelon(S.p)
    processed = 0
    budget_exhausted = False
    for word in words:
        if time.perf_counter() >= deadline:
            budget_exhausted = True
            break
        projected = np.concatenate([
            fold(apply_lie_word(S, word, state), sign)
            for state, sign in zip(states, signs)
        ])
        echelon.add(projected)
        processed += 1
    rank = len(echelon)
    return {
        "tag": "[COMPUTATION]",
        "statement": (
            "Multi-vector evaluation of the listed Lie-word pool is a valid lower "
            "bound on dim g_L, but this cheap pool does not close the L=9 target."
        ),
        "L": L,
        "field": f"F_{S.p}",
        "states": [
            "all_plus_X_basis_vacuum",
            "all_minus_X_basis_full_configuration",
            "rung_staggered_X_basis: even rungs empty, odd rungs fully occupied",
        ],
        "word_pool": {
            "basis": "all left-nested words in D,F,Ddag of length <= word_len",
            "word_len": word_len,
            "candidate_operator_count": len(words),
            "processed_operator_count": processed,
        },
        "projection": {
            "kind": "three independent deterministic signed folds concatenated",
            "seed": seed,
            "width_per_state": width,
            "combined_width": 3 * width,
        },
        "rank_lower_bound_mod_p1": rank,
        "target": 1 << L,
        "target_reached": rank >= (1 << L),
        "candidate_count_precludes_target": len(words) < (1 << L),
        "wall_budget_seconds": time_budget,
        "wall_guard_seconds": WALL_GUARD_SECONDS,
        "wall_seconds_observed": round(time.perf_counter() - t0, 3),
        "wall_budget_exhausted": budget_exhausted,
        "rss_start_bytes_process": rss_start,
        "rss_peak_bytes_process": peak_rss_bytes(),
    }


