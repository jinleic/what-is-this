"""Is the layer transfer operator's SPECTRUM free-fermionic?

A basis-independent test, logically independent of every algebraic no-go in this repository.
`proofs/algebraic_obstruction.md`, `proofs/dolan_grady_defect.md` and
`proofs/tridiagonal_nogo.md` all say the *algebra* generated by the transfer factors is not
a quadratic Clifford algebra.  None of them excludes a "free fermions in disguise" scenario
(Fendley 2019) in which the spectrum is nevertheless exactly that of a Gaussian operator in
some entirely different mode basis.  This experiment closes that gap spectrally.

    LEMMA (spectral Gaussianity).  Let W be a fermionic Gaussian operator on m modes,
    W = C exp(quadratic in Majoranas).  Its 2^m eigenvalues are

        lambda_s = C exp( (1/2) sum_k s_k gamma_k ),   s in {-1,+1}^m,

    so, writing t = log lambda - min log lambda, the multiset {t} is EXACTLY the multiset of
    the 2^m subset sums of the m nonnegative numbers gamma_k.

We use the contrapositive: if the shifted log-spectrum of V is not a subset-sum multiset,
then V is not Gaussian on n modes in ANY choice of Majorana modes -- no Jordan-Wigner
ordering, no local rotation, no relabelling, no basis change whatsoever.

SCOPE OF THE ANCILLA STATEMENT -- read this carefully, it is easy to overclaim.
Running the test on the multiset WITH multiplicities does cover the TRIVIAL ancilla
extension V (x) I_{2^a}, because a generator equal to zero simply doubles every
multiplicity, so V (x) I_{2^a} is Gaussian on n+a modes iff V is Gaussian on n modes.
It does NOT cover a general Gaussian embedding: if V were the restriction of a Gaussian
operator W on n+a modes to an invariant subspace, spec(V) would be a SUBMULTISET of
spec(W), and a submultiset of a subset-sum multiset need not itself be a subset-sum
multiset.  That escape route is not excluded here and is recorded as open.

SCOPE.  Periodic 1D layers are *not* a single Gaussian: Kaufman's solution is a
parity-projected pair, V = (1+P)/2 V_NS + (1-P)/2 V_R, with different single-particle
energies in the two sectors.  The single-family test therefore does not apply to them and
would produce a false negative; their parity sectors are reported separately.  The decisive
controlled comparison -- change exactly one ingredient -- is

    open 1D chain layer (2D Ising strip)   versus   open 2D grid layer (3D Ising).
"""

