Q2, Q3, Q4, Q5 = sp.symbols("Q2 Q3 Q4 Q5")

# The explicit relation proposed during this front.  Its derivation is
# invalidated below; retaining it makes the counterexample reproducible.
CANDIDATE = sp.Poly(
    Q2**4 - 12*Q2**3*Q3 + 30*Q2**2*Q3**2 - 16*Q2**2*Q3
    + 4*Q2**2*Q4 - 4*Q2**2*Q5 - 6*Q2**2
    - 24*Q2*Q3**3 + 16*Q2*Q3**2 - 4*Q2*Q3*Q4 + 16*Q2*Q3
    - 8*Q2*Q5 + 4*Q3**4 + 8*Q3**3 - 2*Q3**2*Q4
    + 8*Q3**2*Q5 - 28*Q3**2 + 8*Q3*Q4 - 8*Q3*Q5 + 8*Q3
    - Q4**2 + 4*Q4*Q5 - 2*Q4 - 4*Q5**2 + 8*Q5 + 4,
    Q2,
    Q3,
    Q4,
    Q5,
    domain=sp.ZZ,
)


def centered_traces(modes: tuple[int, ...], max_order: int = 5) -> list[sp.Expr]:
    roots = [sp.sqrt(mode) for mode in modes]
    return [
        sp.prod(root**order + root ** (-order) for root in roots)
        for order in range(1, max_order + 1)
    ]


