X2 = np.array([[0, 1], [1, 0]], dtype=np.int64)
Z2 = np.array([[1, 0], [0, -1]], dtype=np.int64)
I2 = np.eye(2, dtype=np.int64)
J2 = X2 @ Z2  # [[0,-1],[1,0]]


def pauli_matrix(v: int, n: int) -> np.ndarray:
    M = np.array([[1]], dtype=np.int64)
    for i in range(n):
        a = (v >> i) & 1
        b = (v >> (n + i)) & 1
        letter = J2 if (a and b) else (X2 if a else (Z2 if b else I2))
        M = np.kron(M, letter)
    return M


def bits_matrix(S, n: int) -> np.ndarray:
    S = np.asarray(S, dtype=np.int64)
    return ((S[:, None] >> np.arange(2 * n)[None, :]) & 1).astype(np.int64)


def core_tables(S, n: int):
    """pair: (d,d) anticommutation mask; C: (d,d) structure constants in {0,+-2}."""
    M = bits_matrix(S, n)
    A, B = M[:, :n], M[:, n:]
    pair = ((B @ A.T) + (A @ B.T)) % 2
    s1 = 1 - 2 * ((B @ A.T) % 2)          # (-1)^{b_v . a_j}
    C = s1 - s1.T                          # [Q_v, Q_j] = C[v, j] Q_{v xor j}
    pos = np.full(1 << (2 * n), -1, dtype=np.int64)
    pos[np.asarray(S)] = np.arange(len(S))
    return pair, C, pos, np.asarray(S, dtype=np.int64)


def killing_diagonal(C, pos, Sv) -> np.ndarray:
    """kappa_vv = Tr(ad Q_v ad Q_v) = sum_j c(v,j) c(v, j xor v)  [exact integers]."""
    d = len(Sv)
    P2i = pos[Sv[:, None] ^ Sv[None, :]]
    Cclip = np.where(P2i >= 0, C[np.arange(d)[:, None], np.clip(P2i, 0, d - 1)], 0)
    return (C * Cclip).sum(axis=1)


def trace_identity_check(pair, C, pos, Sv, kap, rng, trials=5) -> bool:
    """Independent verification: Tr(ad x ad y) = sum_v a_v b_v kappa_vv on random combos."""
    d = len(Sv)
    for _ in range(trials):
        supp = rng.choice(d, size=min(20, d), replace=False)
        av = np.zeros(d, dtype=np.int64)
        bv = np.zeros(d, dtype=np.int64)
        av[supp] = rng.integers(-3, 4, size=len(supp))
        bv[supp] = rng.integers(-3, 4, size=len(supp))

        def ad_of(coef):
            Ax = np.zeros((d, d), dtype=np.int64)
            for v in supp:
                js = np.where(pair[v] == 1)[0]
                tgt = pos[Sv[v] ^ Sv[js]]
                Ax[tgt, js] += coef[v] * C[v, js]
            return Ax

        tr_direct = int((ad_of(av) @ ad_of(bv)).trace())
        if tr_direct != int((av * bv * kap).sum()):
            return False
    return True


def derived_support(pair, pos, Sv, subset):
    subset = np.asarray(subset)
    Pm = pair[np.ix_(subset, subset)] == 1
    Psrc = pos[Sv[subset][:, None] ^ Sv[subset][None, :]]
    good = Pm & (Psrc >= 0)
    return sorted(set(Psrc[good].tolist()))


