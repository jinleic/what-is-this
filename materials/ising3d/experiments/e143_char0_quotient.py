def grid_graph(a: int, b: int):
    n = a * b
    idx = lambda x, y: x * b + y
    bonds = []
    for x in range(a):
        for y in range(b):
            if x + 1 < a:
                bonds.append((idx(x, y), idx(x + 1, y)))
            if y + 1 < b:
                bonds.append((idx(x, y), idx(x, y + 1)))
    return list(range(n)), bonds, n


def chain_graph(n: int):
    return list(range(n)), [(i, i + 1) for i in range(n - 1)], n


def tfim_generator_strings(sites, bonds, n):
    """{X_i} u {Z_u Z_v} as symplectic bit-vectors: bit i = a_i (X), bit n+i = b_i (Z)."""
    gens = []
    labels = []
    for i in sites:
        gens.append(1 << i)
        labels.append(f"X_{i}")
    for (u, v) in bonds:
        gens.append((1 << (n + u)) | (1 << (n + v)))
        labels.append(f"Z_{u}Z_{v}")
    return gens, labels


def symplectic(v: int, w: int, n: int) -> int:
    mask = (1 << n) - 1
    bv, av = v >> n, v & mask
    bw, aw = w >> n, w & mask
    return (bin(bv & aw).count("1") + bin(bw & av).count("1")) & 1


def independent_bfs_closure(gens, n: int):
    """Independent BFS closure under symplectic addition (cross-check of ising.clifford)."""
    seen = set(gens)
    frontier = list(gens)
    while frontier:
        new = []
        snapshot = list(seen)
        for v in frontier:
            for w in snapshot:
                if symplectic(v, w, n) == 1:
                    s = v ^ w
                    if s not in seen:
                        seen.add(s)
                        new.append(s)
        frontier = new
    return sorted(seen)

