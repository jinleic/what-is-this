def ambient_classical(half: int, form_type, traceless: bool):
    """Identify the classical ambient algebra containing the image."""
    if form_type == "alternating":
        m = half // 2
        return "sp", m * (2 * m + 1), f"sp({half}) [C_{m}]"
    if form_type == "symmetric":
        return "so", half * (half - 1) // 2, f"so({half}) [{'D' if half % 2 == 0 else 'B'}_{half // 2}]"
    if traceless:
        return "sl", half * half - 1, f"sl({half}) [A_{half - 1}]"
    return "gl", half * half, f"gl({half})"


