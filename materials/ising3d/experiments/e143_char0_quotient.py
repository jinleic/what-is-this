def _rational_reconstruct(a: int, m: int):
    a = int(a) % m
    if a == 0:
        return 0, 1
    r0, r1 = m, a
    s0, s1 = 0, 1
    while r1 * r1 > m:
        q = r0 // r1
        r0, r1 = r1, r0 - q * r1
        s0, s1 = s1, s0 - q * s1
    if r1 == 0 or r1 * r1 > m:
        return None
    return int(s1), int(r1)


def solve_invariant_form(gens_blocks, m, p):
    """All B with X^T B + B X = 0 for every generator block X, over F_p.
    Equation (i,j): sum_k X[k,i] B[k,j] + sum_k B[i,k] X[k,j] = 0, unknowns B row-major.
    Returns (kernel_dim, [kernel basis matrices over F_p])."""
    from collections import defaultdict as dd
    triples = dd(int)
    m2 = m * m
    for gi, X in enumerate(gens_blocks):
        Xp = (X % p).astype(np.int64)
        ks, cols = np.nonzero(Xp)
        base = gi * m2
        for k, i in zip(ks.tolist(), cols.tolist()):
            # term 1: X[k,i] B[k,j] contributes to equation (i,j)
            v = int(Xp[k, i])
            for j in range(m):
                triples[(base + i * m + j, k * m + j)] += v
        for k, j in zip(ks.tolist(), cols.tolist()):
            # term 2: B[i,k] X[k,j] contributes to equation (i,j)
            v = int(Xp[k, j])
            for i in range(m):
                triples[(base + i * m + j, i * m + k)] += v
    Amat = np.zeros((len(gens_blocks) * m2, m2), dtype=np.int64)
    for (eq, var), v in triples.items():
        Amat[eq, var] = (Amat[eq, var] + v) % p
    Amat = Amat[np.abs(Amat).sum(axis=1) > 0]
    ncols = m * m
    r = 0
    piv_cols = []
    for c in range(ncols):
        nz = np.nonzero(Amat[r:, c] % p)[0]
        if len(nz) == 0:
            continue
        piv = r + int(nz[0])
        Amat[[r, piv]] = Amat[[piv, r]]
        Amat[r] = (Amat[r] * pow(int(Amat[r, c]), p - 2, p)) % p
        col = Amat[:, c].copy()
        col[r] = 0
        mask = col % p != 0
        Amat[mask] = (Amat[mask] - np.outer(col[mask], Amat[r])) % p
        piv_cols.append(c)
        r += 1
        if r == len(Amat):
            break
    piv_set = set(piv_cols)
    free = [c for c in range(ncols) if c not in piv_set]
    kern = []
    for f in free:
        v = np.zeros(ncols, dtype=np.int64)
        v[f] = 1
        for i, c in enumerate(piv_cols):
            v[c] = (-Amat[i, f]) % p
        kern.append(v.reshape(m, m))
    return len(free), kern


def reconstruct_integer_form(Bp, p):
    """Rational-reconstruct a mod-p kernel matrix to a small-integer matrix (or None)."""
    from math import gcd
    m = Bp.shape[0]
    rec = []
    for i in range(m):
        row = []
        for j in range(m):
            r = _rational_reconstruct(int(Bp[i, j]), p)
            if r is None:
                return None
            row.append(r)
        rec.append(row)
    den = 1
    for row in rec:
        for _, d in row:
            den = den * d // gcd(den, d)
    B = np.array([[num * (den // d) for num, d in row] for row in rec], dtype=np.int64)
    g = 0
    for x in B.flatten().tolist():
        g = gcd(g, abs(int(x)))
    if g:
        B = (B // g).astype(np.int64)
    return B


