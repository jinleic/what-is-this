def parity_blocks(Mv: np.ndarray, n: int, reps=None):
    """Blocks of Mv in the prod-X parity eigenbasis (integer, entries in {0,+-1})."""
    dim = 1 << n
    comp = dim - 1
    if reps is None:
        reps = [s for s in range(dim) if s < (s ^ comp)]
    half = len(reps)
    Mp = np.zeros((half, half), dtype=np.int64)
    Mm = np.zeros((half, half), dtype=np.int64)
    sb = [s ^ comp for s in reps]
    for ki, s in enumerate(reps):
        r0, r1 = sb[ki], s
        for kj, t in enumerate(reps):
            t0 = sb[kj]
            v0 = Mv[r1, t]
            v1 = Mv[r1, t0]
            v2 = Mv[r0, t]
            v3 = Mv[r0, t0]
            if v0 or v1 or v2 or v3:
                Mp[ki, kj] = (v0 + v1 + v2 + v3) // 2
                Mm[ki, kj] = (v0 - v1 - v2 + v3) // 2
    return Mp, Mm


def rank_mod_p_cert(mats, p: int):
    """rank over F_p of the stacked matrix; returns (rank, pivot_rows, pivot_cols,
    det_minor_mod_p) where det_minor is the determinant mod p of the ORIGINAL stacked
    matrix restricted to pivot rows/cols (nonzero => that integer minor is nonzero mod p
    => nonzero over Z => rank_Q >= rank)."""
    Stack = np.stack(mats).reshape(len(mats), -1).astype(np.int64) % p
    m, ncols = Stack.shape
    r = 0
    orig = list(range(m))
    piv_rows, piv_cols = [], []
    for c in range(ncols):
        nz = np.nonzero(Stack[r:, c] % p)[0]
        if len(nz) == 0:
            continue
        piv = r + int(nz[0])
        Stack[[r, piv]] = Stack[[piv, r]]
        orig[r], orig[piv] = orig[piv], orig[r]
        inv = pow(int(Stack[r, c]), p - 2, p)
        Stack[r] = (Stack[r] * inv) % p
        col = Stack[:, c].copy()
        col[r] = 0
        mask = col % p != 0
        Stack[mask] = (Stack[mask] - np.outer(col[mask], Stack[r])) % p
        piv_rows.append(orig[r])
        piv_cols.append(c)
        r += 1
        if r == m:
            break
    rank = r
    if rank == 0:
        return 0, [], [], 0
    minor = np.stack(mats).reshape(len(mats), -1)[np.ix_(piv_rows, piv_cols)].astype(np.int64) % p
    det = _det_mod_p(minor, p)
    return rank, piv_rows, piv_cols, int(det)


def _det_mod_p(M, p):
    M = M.copy() % p
    n = M.shape[0]
    det = 1
    for i in range(n):
        nz = np.nonzero(M[i:, i] % p)[0]
        if len(nz) == 0:
            return 0
        j = i + int(nz[0])
        if j != i:
            M[[i, j]] = M[[j, i]]
            det = (-det) % p
        piv = int(M[i, i])
        det = (det * piv) % p
        inv = pow(piv, p - 2, p)
        fac = (M[i + 1:, i] * inv) % p
        M[i + 1:] = (M[i + 1:] - np.outer(fac, M[i])) % p
    return int(det % p)


