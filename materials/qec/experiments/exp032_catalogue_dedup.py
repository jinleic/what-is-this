"""EXP-032: catalogue equivalence audit under the proved PBB symmetry group G.

This experiment deliberately tests only the transformations justified by the
ring identities and qubit permutation in proofs/equations.md (E4, E5/R1-R2,
E9) and proofs/pbb_structure.md (R1-R2, Proposition 4):

* common lattice translation tau_(i,j):
      (A, B, C, D) -> (x^i y^j A, x^i y^j B,
                        x^i y^j C, x^i y^j D),
* variable inversion iota, where F* = F(x^-1, y^-1):
      (A, B, C, D) -> (A*, B*, C*, D*),
* transpose/swap sigma:
      (A, B, C, D) -> (B*, A*, D*, C*).

The C,D action in sigma is forced by the PBB convention
H = [A B | C D; 0 0 | B^T A^T].  Under the qubit permutation
(L,g) <-> (R,-g), its first block becomes [B^T A^T | D^T C^T]
and its second block becomes [0 0 | A B], which is exactly the PBB matrix for
(B*, A*, D*, C*).  Inversion alone is induced by g -> -g on both qubit
blocks.  A common translation is an invertible row relabelling: it left
multiplies the first block by T and the second by T^T.  No axis exchange,
general torus automorphism, arbitrary qubit permutation, local Clifford, or
row-space canonicalization is included.

Canonical form is the lexicographically least normalized exponent-set 4-tuple
in the complete orbit generated by those transformations.  The finite discrete
closure is enumerated by breadth-first search; all ell*m translations are then
applied.  Distinctness conclusions are therefore scoped exactly as
"distinct under group G".
"""

