"""EXP-039: parent-level no-go for PBB distance increase (Theorem H).

EXP-036/037/038 all decide *one catalogue row at a time*: each conclusion is
about one perturbation ``[C D]``.  Theorem H moves the quantifier.  Because
``Delta`` is an ``R``-submodule of the ``Z`` sector, a strict distance increase
forces it to swallow the whole module ``M`` generated by the parent's
minimum-weight ``Z``-logicals, so with ``T = dim (M+S_Z)/S_Z``

    d_Q > d_Z(P)   ==>   k_Q <= k_P - T(P)      for EVERY perturbation of P.

``T(P)`` is computed once per *parent*.  When ``T = k_P`` the whole family over
that parent is closed: no perturbation keeps a logical qubit while beating
``d_Z(P)``, including the ones never catalogued.

Falsification gate (the point of the experiment).  Seven certified reversals
are known -- rows where the PBB distance provably *exceeds* the parent's.  Each
supplies an independent adversarial test: Theorem H must PERMIT it, i.e.
``k_pbb <= k_parent - T`` must hold.  A single violation refutes the theorem,
and the run exits nonzero rather than reporting a result.

Run:
    python experiments/exp039_nogo_module.py run [--ns 72 108 144]
    python experiments/exp039_nogo_module.py gate       # falsification only
    python experiments/exp039_nogo_module.py assemble
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

SCHEMA = "exp039-nogo-module-v1"
SOLVER_NAME = "cadical195"
STATE_DIR = ROOT / "results" / "partial_runs" / "exp039"
OUT = ROOT / "results" / "partial_runs" / "exp039_nogo_module.json"
POOL = ROOT / "results" / "partial_runs" / "exp037"

_SPEC = importlib.util.spec_from_file_location(
    "exp027_delta_audit", ROOT / "experiments" / "exp027_delta_audit.py"
)
E27 = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = E27
_SPEC.loader.exec_module(E27)

from qec_research.codes.pbb_nogo import (  # noqa: E402
    NoGoCertificate,
    minimum_weight_module,
)
from qec_research.distance.sat_decide import ENCODING_VERSION  # noqa: E402
from qec_research.gf2.linalg import rank_np  # noqa: E402

# The seven certified reversals: rows where d_PBB > d_parent is proved, each a
# standing adversarial test for any theorem that bounds distance increase.
CERTIFIED_REVERSALS = (
    "phase2_58",
    "phase2_60",
    "phase2_71",
    "phase2_72",
    "phase2_88",
    "9_6_0183",
    "12_6_0217",
)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def atomic_write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(f"{path.suffix}.{os.getpid()}.tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    tmp.replace(path)


def load_pool_lower_bounds() -> dict[str, int]:
    """Certified CSS distance per parent fingerprint, from EXP-037's pool.

    ``min(d_X,d_Z)`` exact implies UNSAT below it on the ``Z`` side, so it is a
    sound *lower* bound for ``d_Z`` -- which is all the closure needs to start.
    """

    out: dict[str, int] = {}
    if not POOL.exists():
        return out
    for path in sorted(POOL.glob("css_*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        if rec.get("exact") and rec.get("encoding_version") == ENCODING_VERSION:
            out[rec["css_fingerprint"]] = int(rec["distance"])
    return out


def distinct_parents(rows: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Fingerprint -> {rows sharing this parent, dimensions}."""

    out: dict[str, dict[str, Any]] = {}
    for index, row in enumerate(rows):
        _, HX, HZ = E27.parent_matrices(row)
        fp = E27.matrix_fingerprint(HX, HZ)
        entry = out.setdefault(
            fp,
            {
                "fingerprint": fp,
                "n": int(HX.shape[1]),
                "ell": int(row["ell"]),
                "m": int(row["m"]),
                "k_parent": int(HX.shape[1]) - int(rank_np(HX)) - int(rank_np(HZ)),
                "members": [],
            },
        )
        entry["members"].append(
            {
                "catalogue_index": index,
                "label": E27.catalogue_label(row, index),
                "k_pbb": int(row["k"]),
            }
        )
    return out


def parent_path(fingerprint: str) -> Path:
    return STATE_DIR / f"parent_{fingerprint[:16]}.json"


def certify_parent(
    entry: dict[str, Any], d_lower: int, *, conflict_budget: int = 0
) -> dict[str, Any]:
    """Compute (or reload) ``T`` for one parent.  Atomic and resumable."""

    path = parent_path(entry["fingerprint"])
    identity = {
        "schema": SCHEMA,
        "fingerprint": entry["fingerprint"],
        "n": entry["n"],
        "k_parent": entry["k_parent"],
        "encoding_version": ENCODING_VERSION,
    }
    if path.exists():
        stored = json.loads(path.read_text(encoding="utf-8"))
        if all(stored.get(key) == value for key, value in identity.items()):
            return stored

    rows = E27.load_catalogue()
    row = rows[entry["members"][0]["catalogue_index"]]
    _, HX, HZ = E27.parent_matrices(row)
    started = time.perf_counter()
    cert: NoGoCertificate = minimum_weight_module(
        HX,
        HZ,
        d_lower,
        entry["ell"],
        entry["m"],
        k_parent=entry["k_parent"],
        solver_name=SOLVER_NAME,
        conflict_budget=conflict_budget,
    )
    payload = {
        **identity,
        "ell": entry["ell"],
        "m": entry["m"],
        "d_z_lower_input": int(d_lower),
        "d_z_parent": cert.d_z_parent,
        "d_z_exact": cert.d_z_exact,
        "T": cert.T,
        "T_is_exact": cert.closed,
        "k_ceiling": cert.k_ceiling,
        "family_closed": cert.family_closed,
        "num_witnesses": len(cert.witnesses),
        "witness_vectors": [w.tolist() for w in cert.witnesses],
        "calls": cert.calls,
        "solver": SOLVER_NAME,
        "wall_time_s": round(time.perf_counter() - started, 2),
        "utc": utc_now(),
    }
    atomic_write_json(path, payload)
    return payload


def load_certificates() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    if not STATE_DIR.exists():
        return out
    for path in sorted(STATE_DIR.glob("parent_*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        if rec.get("schema") == SCHEMA:
            out[rec["fingerprint"]] = rec
    return out


def certified_pbb_lower_bounds() -> dict[str, int]:
    """``label -> c`` where a replayed UNSAT proves ``d_PBB > c``.

    Read from EXP-037's per-row records.  Used only to establish that a gate
    check is *non-vacuous*: Theorem H's hypothesis is ``d_Q > d_Z(P)``, so a
    check only tests the theorem when ``c >= d_Z(P)``.
    """

    out: dict[str, int] = {}
    for path in sorted(POOL.glob("row_*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        label, bound = rec.get("label"), rec.get("certified_lower_gt")
        if label and bound is not None:
            out[str(label)] = int(bound)
    return out


def falsification_gate(
    parents: dict[str, dict[str, Any]], certs: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """Theorem H must permit every certified reversal.  One violation refutes it.

    A refutation needs BOTH halves: the hypothesis ``d_Q > d_Z(P)`` verified by
    a replayed UNSAT lower bound, and the conclusion ``k_Q <= k_P - T``
    violated.  Checks whose hypothesis is not independently established are
    reported but counted as vacuous, never as support.
    """

    pbb_lower = certified_pbb_lower_bounds()
    checks: list[dict[str, Any]] = []
    violations: list[dict[str, Any]] = []
    for fp, entry in parents.items():
        cert = certs.get(fp)
        if cert is None:
            continue
        for member in entry["members"]:
            if member["label"] not in CERTIFIED_REVERSALS:
                continue
            permitted = int(member["k_pbb"]) <= int(cert["k_ceiling"])
            bound = pbb_lower.get(member["label"])
            # d_Q > bound and bound >= d_Z(P)  ==>  d_Q > d_Z(P).  The parent's
            # d_Z and T must themselves be exact: a budget-aborted certificate
            # would make "non-vacuous" vacuous (or a violation a false alarm),
            # so inexactness downgrades the check rather than passing it.
            hypothesis = (
                bound is not None
                and int(bound) >= int(cert["d_z_parent"])
                and bool(cert["d_z_exact"])
                and bool(cert["T_is_exact"])
            )
            check = {
                "label": member["label"],
                "catalogue_index": member["catalogue_index"],
                "n": entry["n"],
                "k_parent": entry["k_parent"],
                "k_pbb": member["k_pbb"],
                "d_z_parent": cert["d_z_parent"],
                "d_pbb_certified_gt": bound,
                "hypothesis_verified": hypothesis,
                "T": cert["T"],
                "T_is_exact": cert["T_is_exact"],
                "k_ceiling": cert["k_ceiling"],
                "permitted_by_theorem_H": permitted,
                "slack": int(cert["k_ceiling"]) - int(member["k_pbb"]),
            }
            checks.append(check)
            if hypothesis and not permitted:
                violations.append(check)
    non_vacuous = [c for c in checks if c["hypothesis_verified"]]
    return {
        "reversals_checked": len(checks),
        "reversals_non_vacuous": len(non_vacuous),
        "reversals_known": len(CERTIFIED_REVERSALS),
        "all_saturate_bound": bool(non_vacuous)
        and all(c["slack"] == 0 for c in non_vacuous),
        "checks": sorted(checks, key=lambda c: c["catalogue_index"]),
        "violations": violations,
        "theorem_refuted": bool(violations),
    }


def classify_rows(
    parents: dict[str, dict[str, Any]], certs: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """Rows the parent-level bound settles with no per-row work at all."""

    decided: list[dict[str, Any]] = []
    permitted: list[dict[str, Any]] = []
    for fp, entry in parents.items():
        cert = certs.get(fp)
        if cert is None:
            continue
        for member in entry["members"]:
            item = {
                "label": member["label"],
                "catalogue_index": member["catalogue_index"],
                "n": entry["n"],
                "k_parent": entry["k_parent"],
                "k_pbb": member["k_pbb"],
                "T": cert["T"],
                "k_ceiling": cert["k_ceiling"],
                "d_z_parent": cert["d_z_parent"],
            }
            if int(member["k_pbb"]) > int(cert["k_ceiling"]):
                decided.append(item)  # d_Q <= d_Z(parent), proved a priori
            else:
                permitted.append(item)
    return {
        "rows_capped_a_priori": sorted(decided, key=lambda c: c["catalogue_index"]),
        "rows_theorem_permits": sorted(permitted, key=lambda c: c["catalogue_index"]),
    }


def run(args: argparse.Namespace) -> int:
    rows = E27.load_catalogue()
    parents = distinct_parents(rows)
    bounds = load_pool_lower_bounds()

    targets = []
    for fp, entry in parents.items():
        if args.ns and entry["n"] not in set(args.ns):
            continue
        # The pool record is only a speedup: weight 2 is a trivially valid
        # certified lower bound, and the closure's cap climb pins d_Z either
        # way.  Theorem H therefore needs no CSS frontier of its own.
        targets.append((entry["n"], fp, entry))
    targets.sort(key=lambda t: (t[0], t[1]))
    if args.stride > 1:
        targets = targets[args.offset :: args.stride]
    print(f"parents selected: {len(targets)} (of {len(parents)} distinct)", flush=True)

    for n, fp, entry in targets:
        try:
            payload = certify_parent(
                entry, bounds.get(fp, 2), conflict_budget=args.conflict_budget
            )
        except Exception as exc:  # noqa: BLE001 - one parent must not kill the run
            print(f"n={n:4d} {fp[:12]} FAILED: {exc}", flush=True)
            continue
        print(
            f"n={n:4d} {fp[:12]} k_P={payload['k_parent']:3d} "
            f"d_Z={payload['d_z_parent']:3d} T={payload['T']:3d} "
            f"exact={payload['T_is_exact']} k_ceiling={payload['k_ceiling']:3d} "
            f"family_closed={payload['family_closed']} "
            f"rows={len(entry['members'])} {payload['wall_time_s']}s",
            flush=True,
        )
    return 0


def assemble(args: argparse.Namespace) -> dict[str, Any]:
    rows = E27.load_catalogue()
    parents = distinct_parents(rows)
    certs = load_certificates()
    gate = falsification_gate(parents, certs)
    rows_class = classify_rows(parents, certs)

    closed = [c for c in certs.values() if c["family_closed"]]
    exact = [c for c in certs.values() if c["T_is_exact"]]
    by_n: dict[str, dict[str, int]] = {}
    for cert in certs.values():
        slot = by_n.setdefault(
            str(cert["n"]), {"parents": 0, "family_closed": 0, "T_exact": 0}
        )
        slot["parents"] += 1
        slot["family_closed"] += int(bool(cert["family_closed"]))
        slot["T_exact"] += int(bool(cert["T_is_exact"]))

    payload = {
        "experiment": "EXP-039",
        "schema": SCHEMA,
        "protocol": __doc__,
        "encoding_version": ENCODING_VERSION,
        "solver": SOLVER_NAME,
        "generated_utc": utc_now(),
        "counts": {
            "distinct_parents_total": len(parents),
            "parents_certified": len(certs),
            "parents_T_exact": len(exact),
            "parents_family_closed": len(closed),
            "catalogue_rows_capped_a_priori": len(rows_class["rows_capped_a_priori"]),
            "catalogue_rows_theorem_permits": len(rows_class["rows_theorem_permits"]),
        },
        "by_n": by_n,
        "falsification_gate": gate,
        "family_closed_parents": sorted(
            (
                {
                    "fingerprint": c["fingerprint"][:16],
                    "n": c["n"],
                    "k_parent": c["k_parent"],
                    "d_z_parent": c["d_z_parent"],
                    "T": c["T"],
                    "num_witnesses": c["num_witnesses"],
                }
                for c in closed
            ),
            key=lambda c: (c["n"], c["fingerprint"]),
        ),
        **rows_class,
    }
    atomic_write_json(OUT, payload)
    return payload


def gate_only(args: argparse.Namespace) -> int:
    rows = E27.load_catalogue()
    gate = falsification_gate(distinct_parents(rows), load_certificates())
    print(json.dumps(gate, indent=2, sort_keys=True))
    if gate["theorem_refuted"]:
        print("\nTHEOREM H REFUTED by the reversals above.", flush=True)
        return 1
    print(
        f"\ngate passed: {gate['reversals_checked']}/{gate['reversals_known']} "
        "certified reversals are permitted",
        flush=True,
    )
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    runner = sub.add_parser("run")
    runner.add_argument("--ns", type=int, nargs="*", help="restrict to code lengths")
    runner.add_argument("--conflict-budget", type=int, default=0)
    runner.add_argument("--offset", type=int, default=0)
    runner.add_argument("--stride", type=int, default=1)
    sub.add_parser("gate")
    sub.add_parser("assemble")
    return parser


def main() -> int:
    args = build_parser().parse_args()
    if args.command == "run":
        return run(args)
    if args.command == "gate":
        return gate_only(args)
    summary = assemble(args)
    print(json.dumps(summary["counts"], indent=2, sort_keys=True))
    print(
        "falsification gate:",
        "REFUTED" if summary["falsification_gate"]["theorem_refuted"] else "PASSED",
        f"({summary['falsification_gate']['reversals_checked']} reversals checked)",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if summary["falsification_gate"]["theorem_refuted"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
