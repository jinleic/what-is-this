def _sha256_file(path):
    digest = hashlib.sha256()
    try:
        with Path(path).open("rb") as stream:
            while True:
                block = stream.read(1024 * 1024)
                if not block:
                    break
                digest.update(block)
    except OSError as exc:
        raise VerificationError("cannot hash %s" % path) from exc
    return digest.hexdigest()


def _regular_file(path, label):
    path = Path(path)
    try:
        metadata = path.lstat()
    except OSError as exc:
        raise VerificationError("cannot stat %s" % label) from exc
    if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode):
        raise VerificationError("%s must be a regular non-symlink file" % label)
    return metadata


def _safe_campaign_member(campaign, relative, label):
    if not isinstance(relative, str) or not relative:
        raise VerificationError("%s path is invalid" % label)
    pure = PurePosixPath(relative)
    if pure.is_absolute() or ".." in pure.parts or "." in pure.parts:
        raise VerificationError("%s path escapes the campaign" % label)
    candidate = campaign.joinpath(*pure.parts)
    resolved_campaign = campaign.resolve()
    try:
        resolved = candidate.resolve(strict=True)
    except OSError as exc:
        raise VerificationError("cannot resolve %s" % label) from exc
    if resolved.parent != resolved_campaign and resolved_campaign not in resolved.parents:
        raise VerificationError("%s resolves outside the campaign" % label)
    return candidate


def _verify_record(path, record, label):
    if not isinstance(record, dict):
        raise VerificationError("%s lock record is not an object" % label)
    expected_fields = {"path", "raw_sha256", "size"}
    if not expected_fields.issubset(record):
        raise VerificationError("%s lock record is incomplete" % label)
    metadata = _regular_file(path, label)
    size = record["size"]
    if isinstance(size, bool) or not isinstance(size, int) or size < 0:
        raise VerificationError("%s locked size is invalid" % label)
    if metadata.st_size != size:
        raise VerificationError("%s size differs from the lock" % label)
    observed = _sha256_file(path)
    expected = record["raw_sha256"]
    if not isinstance(expected, str) or observed != expected:
        raise VerificationError("%s SHA-256 differs from the lock" % label)
    return observed


def _verify_snapshot(campaign, snapshot):
    if not isinstance(snapshot, dict) or not snapshot:
        raise VerificationError("lock snapshot is missing")
    verified = {}
    for name in sorted(snapshot):
        record = snapshot[name]
        if not isinstance(record, dict) or set(record) != {"path", "sha256", "size"}:
            raise VerificationError("snapshot record %s is malformed" % name)
        path = _safe_campaign_member(campaign, record["path"], "snapshot %s" % name)
        metadata = _regular_file(path, "snapshot %s" % name)
        if metadata.st_size != record["size"]:
            raise VerificationError("snapshot %s size differs from lock" % name)
        digest = _sha256_file(path)
        if digest != record["sha256"]:
            raise VerificationError("snapshot %s SHA-256 differs from lock" % name)
        verified[name] = digest
    return verified


def _embedded_hash(document, field, expected, label):
    if not isinstance(document, dict):
        raise VerificationError("%s is not a JSON object" % label)
    supplied = document.get(field)
    if not isinstance(supplied, str):
        raise VerificationError("%s lacks %s" % (label, field))
    payload = dict(document)
    del payload[field]
    observed = hashlib.sha256(_canonical_json(payload)).hexdigest()
    if supplied != observed or supplied != expected:
        raise VerificationError("%s canonical object hash is invalid" % label)


def _load_frozen_configuration(lock_path, campaign_path, slice_index):
    lock_path, campaign = Path(lock_path), Path(campaign_path)
    _regular_file(lock_path, "campaign lock")
    lock_raw = lock_path.read_bytes()
    lock = _decode_json_bytes(lock_raw, "campaign lock")
    lock_sha = hashlib.sha256(lock_raw).hexdigest()
    if not isinstance(lock, dict) or lock.get("schema") != "uc-campaign-lock-v1":
        raise VerificationError("campaign lock schema is unsupported")
    expected_environment = lock.get("expected_environment")
    if not isinstance(expected_environment, dict):
        raise VerificationError("campaign lock lacks expected environment")
    try:
        flint_version = importlib_metadata.version("python-flint")
    except importlib_metadata.PackageNotFoundError as exc:
        raise VerificationError("python-flint distribution metadata is unavailable") from exc
    observed_environment = {
        "python": platform.python_version(),
        "python_implementation": sys.implementation.name,
        "platform": platform.platform(),
        "flint": flint_version,
    }
    if observed_environment["python"] != expected_environment.get("python"):
        raise VerificationError("Python version differs from campaign lock")
    if (observed_environment["python_implementation"].lower()
            != str(expected_environment.get("python_implementation", "")).lower()):
        raise VerificationError("Python implementation differs from campaign lock")
    if observed_environment["platform"] != expected_environment.get("platform"):
        raise VerificationError("platform identity differs from campaign lock")
    if observed_environment["flint"] != expected_environment.get("flint"):
        raise VerificationError("python-flint version differs from campaign lock")
    try:
        resolved_campaign = campaign.resolve(strict=True)
    except OSError as exc:
        raise VerificationError("campaign directory cannot be resolved") from exc
    if not resolved_campaign.is_dir() or campaign.is_symlink():
        raise VerificationError("campaign must be a real directory, not a symlink")
    if resolved_campaign.name != lock.get("campaign_directory_name"):
        raise VerificationError("campaign directory name differs from lock")
    if isinstance(slice_index, bool) or not isinstance(slice_index, int):
        raise VerificationError("slice must be an integer")
    slices = lock.get("slices")
    if not isinstance(slices, list) or not (0 <= slice_index < len(slices)):
        raise VerificationError("slice is outside the locked campaign range")
    slice_record = slices[slice_index]
    if not isinstance(slice_record, dict) or slice_record.get("slice") != slice_index:
        raise VerificationError("slice lock record is malformed")

    launch_record = lock.get("launch")
    launch_path = _safe_campaign_member(
        resolved_campaign, launch_record.get("path") if isinstance(launch_record, dict) else None,
        "launch",
    )
    launch_sha = _verify_record(launch_path, launch_record, "launch")
    launch = _decode_json_bytes(launch_path.read_bytes(), "launch")
    _embedded_hash(launch, "launch_sha256", launch_record.get("object_sha256"), "launch")
    if launch.get("campaign_id") != lock.get("campaign_id"):
        raise VerificationError("launch campaign id differs from lock")
    if launch.get("code_sha256") != lock.get("code_sha256"):
        raise VerificationError("launch code hash differs from lock")
    if launch.get("schema") != "cert3-campaign-v2":
        raise VerificationError("launch schema is unsupported")

    _verify_snapshot(resolved_campaign, lock.get("snapshot"))

    runs = launch.get("runs")
    if not isinstance(runs, list) or len(runs) != len(slices):
        raise VerificationError("launch runs do not match locked slices")
    run = runs[slice_index]
    if not isinstance(run, dict) or run.get("slice") != slice_index:
        raise VerificationError("launch run does not match requested slice")
    if run.get("run_id") != slice_record.get("run_id"):
        raise VerificationError("launch run id differs from lock")

    trace_record = slice_record.get("trace")
    if not isinstance(trace_record, dict) or trace_record.get("schema") != "cert3-trace-v1":
        raise VerificationError("trace lock record is malformed")
    trace_path = _safe_campaign_member(
        resolved_campaign, trace_record.get("path"), "trace"
    )
    trace_metadata = _regular_file(trace_path, "trace")
    if trace_metadata.st_size != trace_record.get("size"):
        raise VerificationError("trace size differs from lock")
    trace_sha = _sha256_file(trace_path)
    if trace_sha != trace_record.get("sha256"):
        raise VerificationError("trace SHA-256 differs from lock")
    if run.get("trace_filename") != trace_record.get("path"):
        raise VerificationError("launch trace filename differs from lock")

    result_record = slice_record.get("result")
    result_path = _safe_campaign_member(
        resolved_campaign,
        result_record.get("path") if isinstance(result_record, dict) else None,
        "result",
    )
    result_sha = _verify_record(result_path, result_record, "result")
    result = _decode_json_bytes(result_path.read_bytes(), "result")
    _embedded_hash(result, "record_sha256", result_record.get("record_sha256"), "result")
    if (result.get("result_schema") != "cert3-result-v2"
            or result.get("slice") != slice_index
            or result.get("run_id") != slice_record.get("run_id")
            or result.get("campaign_id") != lock.get("campaign_id")
            or result.get("trace_sha256") != trace_sha
            or result.get("trace_size") != trace_metadata.st_size
            or result.get("trace_schema") != "cert3-trace-v1"
            or result.get("complete") is not True
            or result.get("returned_normally") is not True
            or result.get("supervisor_committed") is not True
            or result.get("verdict") != "COMPLETE"):
        raise VerificationError("frozen result metadata is not a committed COMPLETE run")

    parameters = launch.get("parameters")
    if not isinstance(parameters, dict):
        raise VerificationError("launch parameters are missing")
    if parameters.get("work_prec_bits") != REPLAY_PREC_BITS:
        raise VerificationError("launch does not lock 80-bit replay arithmetic")
    if parameters.get("alpha") != ALPHA_TEXT:
        raise VerificationError("launch alpha differs from independent formula")
    if Fraction(str(parameters.get("q2pin"))) != Q2_PIN:
        raise VerificationError("launch q2 pin differs from endpoint lemma")
    t_decimal = parameters.get("t_decimal")
    if t_decimal != launch.get("t_decimal") or t_decimal != result.get("t_decimal"):
        raise VerificationError("target decimal differs across frozen inputs")
    t_upper = target_upper_fraction(t_decimal)
    if t_decimal == PINNED_TARGET and t_upper != PINNED_TARGET_UPPER:
        raise VerificationError("pinned 80-bit target upper endpoint changed")

    lambda_family = parameters.get("lambda_family")
    if not isinstance(lambda_family, list) or not lambda_family:
        raise VerificationError("launch lambda family is missing")
    lambda_family = tuple(str(value) for value in lambda_family)
    previous = ctx.prec
    try:
        ctx.prec = REPLAY_PREC_BITS
        if not all(_a(value).is_finite() and _a(value) >= ZERO
                   for value in lambda_family):
            raise VerificationError("launch contains a negative or non-finite lambda")
    finally:
        ctx.prec = previous
    if not all(value in lambda_family for value in PINNED_CENTER_LAMBDAS):
        raise VerificationError("pinned center lambdas are absent from launch family")

    try:
        w_lo, w_hi = Fraction(slice_record["w_lo"]), Fraction(slice_record["w_hi"])
    except (KeyError, ValueError, TypeError, ZeroDivisionError) as exc:
        raise VerificationError("slice weight interval is malformed") from exc
    if run.get("w_lo") != slice_record.get("w_lo") or run.get("w_hi") != slice_record.get("w_hi"):
        raise VerificationError("launch and lock weight intervals differ")
    if not (Fraction(0) <= w_lo < w_hi <= Fraction(1)):
        raise VerificationError("slice weight interval is invalid")
    root = ((0.0, 1.0),) * 4 + ((float(w_lo), float(w_hi)),)

    expected = slice_record.get("expected_replay_tallies")
    if not isinstance(expected, dict) or set(expected) != set(TALLY_NAMES):
        raise VerificationError("locked replay tallies are malformed")
    result_tallies = result.get("tallies")
    if not isinstance(result_tallies, dict):
        raise VerificationError("result tallies are missing")
    for name in TALLY_NAMES:
        if result_tallies.get(name) != expected[name]:
            raise VerificationError("result tally %s differs from lock" % name)
    completion = slice_record.get("expected_completion_tallies")
    if completion != {"budget_boxes": 0, "budget_time": 0, "stack": 0}:
        raise VerificationError("completion tallies do not certify an empty DFS stack")
    if expected["processed"] != trace_metadata.st_size:
        raise VerificationError("processed tally differs from one-byte trace size")

    face_min_width = parameters.get("face_min_width")
    face_box_budget = parameters.get("face_box_budget")
    try:
        face_min_width = float(face_min_width)
    except (TypeError, ValueError, OverflowError) as exc:
        raise VerificationError("launch face width is invalid") from exc
    if (not math.isfinite(face_min_width) or face_min_width <= 0
            or isinstance(face_box_budget, bool)
            or not isinstance(face_box_budget, int) or face_box_budget <= 0):
        raise VerificationError("launch face branch-and-bound limits are invalid")

    verifier_sha = _sha256_file(Path(__file__).resolve())
    binding = {
        "schema": "uc-independent-checkpoint-binding-v1",
        "verifier_sha256": verifier_sha,
        "lock_sha256": lock_sha,
        "launch_raw_sha256": launch_sha,
        "trace_sha256": trace_sha,
        "trace_size": trace_metadata.st_size,
        "result_raw_sha256": result_sha,
        "campaign_id": lock["campaign_id"],
        "run_id": slice_record["run_id"],
        "slice": slice_index,
        "target": t_decimal,
        "target_upper_numerator": str(t_upper.numerator),
        "target_upper_denominator": str(t_upper.denominator),
        "root": _serialise_box(root),
        "lambdas": list(lambda_family),
        "center_lambdas": list(PINNED_CENTER_LAMBDAS),
        "face_min_width": repr(face_min_width),
        "face_box_budget": face_box_budget,
    }
    return {
        "lock": lock,
        "lock_path": lock_path,
        "launch_path": launch_path,
        "result_path": result_path,
        "environment": observed_environment,
        "lock_sha256": lock_sha,
        "launch_sha256": launch_sha,
        "trace_sha256": trace_sha,
        "result_sha256": result_sha,
        "trace_path": trace_path,
        "trace_metadata": trace_metadata,
        "root": root,
        "t_decimal": t_decimal,
        "t_upper": t_upper,
        "lambdas": lambda_family,
        "center_lambdas": PINNED_CENTER_LAMBDAS,
        "face_min_width": face_min_width,
        "face_box_budget": face_box_budget,
        "expected": expected,
        "binding": binding,
        "slice_record": slice_record,
        "verifier_sha256": verifier_sha,
    }


def _seal_report(report):
    sealed = dict(report)
    sealed.pop("report_sha256", None)
    sealed["report_sha256"] = hashlib.sha256(_canonical_json(sealed)).hexdigest()
    return sealed


def audit_campaign_slice(
    lock_path,
    campaign_path,
    slice_index,
    *,
    runtime_seal_path,
    max_events=None,
    checkpoint_path=None,
    resume=False,
):
    """Authenticate and replay one campaign slice.

    A finite ``max_events`` always yields ``PARTIAL_AUDIT`` by policy, even if
    the supplied bound reaches EOF.  PASS additionally requires authenticated
    EOF, an empty DFS stack, and exact locked tallies.
    """
    if resume and max_events is None:
        raise VerificationError(
            "checkpoint resume is integrity-only and cannot produce a full PASS"
        )
    started = time.monotonic()
    started_utc = _datetime.datetime.now(_datetime.timezone.utc).isoformat()
    runtime_seal = _validate_runtime_seal(runtime_seal_path)
    configuration = _load_frozen_configuration(
        lock_path, campaign_path, slice_index
    )
    configuration["binding"] = dict(configuration["binding"])
    configuration["binding"]["runtime_seal_raw_sha256"] = runtime_seal[
        "raw_sha256"
    ]
    replay = replay_trace(
        configuration["trace_path"],
        configuration["root"],
        configuration["t_decimal"],
        configuration["lambdas"],
        face_min_width=configuration["face_min_width"],
        face_box_budget=configuration["face_box_budget"],
        center_lambdas=configuration["center_lambdas"],
        expected_tallies=configuration["expected"],
        max_events=max_events,
        checkpoint_path=checkpoint_path,
        resume=resume,
        checkpoint_binding=configuration["binding"],
    )
    current_verifier_sha = _sha256_file(Path(__file__).resolve())
    if current_verifier_sha != configuration["verifier_sha256"]:
        raise VerificationError("verifier source changed during replay")
    current_trace = _regular_file(configuration["trace_path"], "trace")
    original_trace = configuration["trace_metadata"]
    if (current_trace.st_dev, current_trace.st_ino, current_trace.st_size,
            current_trace.st_mtime_ns) != (
            original_trace.st_dev, original_trace.st_ino,
            original_trace.st_size, original_trace.st_mtime_ns):
        raise VerificationError("trace file changed during replay")
    if _sha256_file(configuration["trace_path"]) != configuration["trace_sha256"]:
        raise VerificationError("trace SHA-256 changed during replay")
    for label, path, expected_sha in (
        ("campaign lock", configuration["lock_path"], configuration["lock_sha256"]),
        ("launch", configuration["launch_path"], configuration["launch_sha256"]),
        ("result", configuration["result_path"], configuration["result_sha256"]),
    ):
        if _sha256_file(path) != expected_sha:
            raise VerificationError("%s SHA-256 changed during replay" % label)
    if _validate_runtime_seal(runtime_seal_path) != runtime_seal:
        raise VerificationError("runtime seal or sealed bytes changed during replay")

    arithmetic_complete = bool(
        replay["eof"]
        and replay["pending_stack"] == 0
        and replay["tallies_verified"]
        and replay["initial_trace_offset"] == 0
        and replay["resume_used"] is False
    )
    if max_events is None:
        if not arithmetic_complete:
            raise VerificationError("full replay did not meet PASS conditions")
        outcome = "PASS"
    else:
        outcome = "PARTIAL_AUDIT"

    report = {
        "schema": "uc-independent-arithmetic-report-v1",
        "outcome": outcome,
        "claim_status": (
            "MACHINE-VERIFIED" if outcome == "PASS"
            else "COMPUTATIONAL-EVIDENCE"
        ),
        "campaign_id": configuration["lock"]["campaign_id"],
        "run_id": configuration["slice_record"]["run_id"],
        "slice": slice_index,
        "processed": replay["processed"],
        "pending_stack": replay["pending_stack"],
        "trace_offset": replay["trace_offset"],
        "trace_eof": replay["eof"],
        "arithmetic_complete": arithmetic_complete,
        "finite_event_limit": max_events,
        "tallies": {name: replay[name] for name in TALLY_NAMES},
        "expected_tallies_authenticated": replay["tallies_verified"],
        "initial_trace_offset": replay["initial_trace_offset"],
        "resume_used": replay["resume_used"],
        "implementation": {
            "gradient_engine": "interval automatic differentiation",
            "imports_frozen_arithmetic": False,
            "rediscover_face_proofs": True,
            "shares_python_flint": True,
            "byte_zero_required_for_pass": True,
        },
        "precision": {
            "global_cover_bits": NATIVE_PREC_BITS,
            "replay_bits": REPLAY_PREC_BITS,
            "cover_cells": GLOBAL_COVER_CELLS,
        },
        "target": {
            "decimal": configuration["t_decimal"],
            "upper_fraction": "%d/%d" % (
                configuration["t_upper"].numerator,
                configuration["t_upper"].denominator,
            ),
        },
        "input_sha256": {
            "lock": configuration["lock_sha256"],
            "launch": configuration["launch_sha256"],
            "trace": configuration["trace_sha256"],
            "result": configuration["result_sha256"],
            "verifier": configuration["verifier_sha256"],
        },
        "runtime_seal": runtime_seal,
        "environment": configuration["environment"],
        "limitations": [
            "The verifier consumes the same authenticated one-byte DFS trace partition.",
            "The verifier and campaign both rely on python-flint's Arb primitive library.",
            "No frozen campaign Python arithmetic module is imported or executed.",
            "Nonnegative lambda values are authenticated launch inputs, not independently rediscovered optimizers.",
        ],
        "elapsed_seconds": time.monotonic() - started,
        "started_utc": started_utc,
        "finished_utc": _datetime.datetime.now(
            _datetime.timezone.utc
        ).isoformat(),
    }
    return _seal_report(report)


def _failure_report(error, arguments):
    text = str(error)
    event_match = re.search(r"trace event ([0-9]+) \(opcode ([0-9]+)\)", text)
    report = {
        "schema": "uc-independent-arithmetic-report-v1",
        "outcome": "FAIL",
        "claim_status": "FAILED",
        "error_type": type(error).__name__,
        "error": text,
        "slice": getattr(arguments, "slice", None),
        "processed": (
            int(event_match.group(1)) - 1 if event_match is not None else None
        ),
        "failing_event": (
            int(event_match.group(1)) if event_match is not None else None
        ),
        "failing_opcode": (
            int(event_match.group(2)) if event_match is not None else None
        ),
        "pending_stack": None,
        "input_sha256": {
            "verifier": _sha256_file(Path(__file__).resolve()),
        },
        "finished_utc": _datetime.datetime.now(
            _datetime.timezone.utc
        ).isoformat(),
    }
    return _seal_report(report)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Independently replay one authenticated UC Campaign I slice"
    )
    parser.add_argument("--lock", required=True)
    parser.add_argument("--campaign", required=True)
    parser.add_argument("--slice", required=True, type=int)
    parser.add_argument("--output", required=True)
    parser.add_argument("--runtime-seal", required=True)
    parser.add_argument("--checkpoint")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--max-events", type=int)
    arguments = parser.parse_args(argv)
    if arguments.resume and not arguments.checkpoint:
        parser.error("--resume requires --checkpoint")
    print(
        "independent arithmetic replay START slice=%d%s"
        % (
            arguments.slice,
            " resume" if arguments.resume else "",
        ),
        flush=True,
    )

    try:
        report = audit_campaign_slice(
            arguments.lock,
            arguments.campaign,
            arguments.slice,
            runtime_seal_path=arguments.runtime_seal,
            max_events=arguments.max_events,
            checkpoint_path=arguments.checkpoint,
            resume=arguments.resume,
        )
        _atomic_write(arguments.output, _canonical_json(report) + b"\n")
    except Exception as exc:
        failure = _failure_report(exc, arguments)
        try:
            _atomic_write(arguments.output, _canonical_json(failure) + b"\n")
        except OSError:
            pass
        print("independent arithmetic replay FAIL: %s" % exc, file=sys.stderr)
        return 1

    if report["outcome"] != "PASS":
        print("independent arithmetic replay PARTIAL_AUDIT", file=sys.stderr)
        return 2
    print("independent arithmetic replay PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
