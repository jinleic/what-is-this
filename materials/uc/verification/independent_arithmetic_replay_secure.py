def _canonical_json(value):
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=True,
        allow_nan=False,
    ).encode("utf-8")


def _checkpoint_key(binding):
    return hashlib.sha256(b"uc-independent-checkpoint-v1\0" + _canonical_json(binding)).digest()


def _serialise_box(box):
    return [[repr(float(lo)), repr(float(hi))] for lo, hi in box]


def _deserialise_box(record):
    if not isinstance(record, list) or len(record) != 5:
        raise VerificationError("checkpoint box has the wrong dimension")
    box = []
    for pair in record:
        if not isinstance(pair, list) or len(pair) != 2:
            raise VerificationError("checkpoint box has a malformed interval")
        try:
            lo, hi = float(pair[0]), float(pair[1])
        except (TypeError, ValueError, OverflowError) as exc:
            raise VerificationError("checkpoint endpoint is invalid") from exc
        if not (math.isfinite(lo) and math.isfinite(hi) and 0 <= lo <= hi <= 1):
            raise VerificationError("checkpoint endpoint is out of range")
        if repr(lo) != pair[0] or repr(hi) != pair[1]:
            raise VerificationError("checkpoint endpoint is not canonical")
        box.append((lo, hi))
    return tuple(box)


def _atomic_write(path, payload):
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        prefix=".%s." % destination.name, suffix=".tmp", dir=destination.parent
    )
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
    except BaseException:
        # Preserve a partial temporary file as failure evidence.  Cleanup is an
        # explicit operator decision, never an implicit verifier side effect.
        raise


def _write_checkpoint(path, binding, trace_offset, stack, counts, eof):
    payload = {
        "schema": "uc-independent-checkpoint-v1",
        "binding": binding,
        "trace_offset": trace_offset,
        "stack": [_serialise_box(box) for box in stack],
        "tallies": {name: int(counts[name]) for name in TALLY_NAMES},
        "eof": bool(eof),
    }
    tag = hmac.new(
        _checkpoint_key(binding), _canonical_json(payload), hashlib.sha256
    ).hexdigest()
    envelope = {"payload": payload, "authentication": {
        "algorithm": "HMAC-SHA256", "tag": tag,
    }}
    _atomic_write(path, _canonical_json(envelope) + b"\n")


def _reject_json_constant(token):
    raise VerificationError("non-finite JSON constant %s" % token)


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise VerificationError("duplicate JSON key %r" % key)
        result[key] = value
    return result


def _decode_json_bytes(raw, label):
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise VerificationError("%s is not UTF-8 JSON" % label) from exc
    try:
        return json.loads(
            text, object_pairs_hook=_unique_object,
            parse_constant=_reject_json_constant,
        )
    except VerificationError:
        raise
    except (json.JSONDecodeError, ValueError, TypeError) as exc:
        raise VerificationError("%s is malformed JSON" % label) from exc


def _validate_runtime_seal(path):
    seal_path = Path(path)
    _regular_file(seal_path, "runtime seal")
    raw = seal_path.read_bytes()
    report = _decode_json_bytes(raw, "runtime seal")
    if (not isinstance(report, dict)
            or report.get("schema") != "uc-runtime-environment-seal-v1"
            or report.get("outcome") != "PASS"
            or report.get("claim_status") != "MACHINE-VERIFIED"):
        raise VerificationError("runtime seal claim envelope is invalid")
    supplied_hash = report.get("report_sha256")
    reduced = {
        key: value for key, value in report.items() if key != "report_sha256"
    }
    if supplied_hash != hashlib.sha256(_canonical_json(reduced)).hexdigest():
        raise VerificationError("runtime seal self-hash differs")
    files = report.get("files")
    if not isinstance(files, list) or not files:
        raise VerificationError("runtime seal file inventory is missing")
    observed_paths = set()
    for record in files:
        if not isinstance(record, dict):
            raise VerificationError("runtime seal file record is malformed")
        file_path = Path(record.get("path", ""))
        resolved = file_path.resolve(strict=True)
        if resolved in observed_paths:
            raise VerificationError("runtime seal repeats a file path")
        observed_paths.add(resolved)
        metadata = _regular_file(resolved, "runtime-sealed file")
        if metadata.st_size != record.get("size"):
            raise VerificationError("runtime-sealed file size differs")
        if _sha256_file(resolved) != record.get("sha256"):
            raise VerificationError("runtime-sealed file SHA-256 differs")
    verifier_record = report.get("independent_verifier")
    current_source = Path(__file__).resolve()
    if (not isinstance(verifier_record, dict)
            or Path(verifier_record.get("path", "")).resolve() != current_source
            or verifier_record.get("size") != current_source.stat().st_size
            or verifier_record.get("sha256") != _sha256_file(current_source)):
        raise VerificationError("runtime seal does not bind this verifier")
    if report.get("file_count") != len(files):
        raise VerificationError("runtime seal file count differs")
    return {
        "path": str(seal_path.resolve()),
        "raw_sha256": hashlib.sha256(raw).hexdigest(),
        "report_sha256": supplied_hash,
        "file_count": len(files),
    }


def _load_checkpoint(path, expected_binding):
    checkpoint_path = Path(path)
    try:
        size = checkpoint_path.stat().st_size
    except OSError as exc:
        raise VerificationError("cannot stat resume checkpoint") from exc
    if size > 512 * 1024 * 1024:
        raise VerificationError("resume checkpoint is unreasonably large")
    try:
        envelope = _decode_json_bytes(checkpoint_path.read_bytes(), "checkpoint")
    except OSError as exc:
        raise VerificationError("cannot read resume checkpoint") from exc
    if not isinstance(envelope, dict) or set(envelope) != {"payload", "authentication"}:
        raise VerificationError("checkpoint envelope has unexpected fields")
    payload, authentication = envelope["payload"], envelope["authentication"]
    if not isinstance(payload, dict) or not isinstance(authentication, dict):
        raise VerificationError("checkpoint envelope has invalid field types")
    if authentication.get("algorithm") != "HMAC-SHA256":
        raise VerificationError("checkpoint authentication algorithm is unsupported")
    supplied = authentication.get("tag")
    if not isinstance(supplied, str) or len(supplied) != 64:
        raise VerificationError("checkpoint authentication tag is malformed")
    binding = payload.get("binding")
    if binding != expected_binding:
        raise VerificationError("checkpoint is bound to different frozen inputs")
    expected = hmac.new(
        _checkpoint_key(expected_binding), _canonical_json(payload), hashlib.sha256
    ).hexdigest()
    if not hmac.compare_digest(supplied, expected):
        raise VerificationError("checkpoint authentication failed")
    if payload.get("schema") != "uc-independent-checkpoint-v1":
        raise VerificationError("checkpoint schema is unsupported")
    offset = payload.get("trace_offset")
    if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
        raise VerificationError("checkpoint trace offset is invalid")
    raw_tallies = payload.get("tallies")
    if not isinstance(raw_tallies, dict) or set(raw_tallies) != set(TALLY_NAMES):
        raise VerificationError("checkpoint tallies are malformed")
    counts = Counter()
    for name in TALLY_NAMES:
        value = raw_tallies[name]
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise VerificationError("checkpoint tally is invalid")
        counts[name] = value
    if counts["processed"] != offset:
        raise VerificationError("checkpoint offset and processed tally differ")
    raw_stack = payload.get("stack")
    if not isinstance(raw_stack, list):
        raise VerificationError("checkpoint stack is malformed")
    stack = [_deserialise_box(box) for box in raw_stack]
    eof = payload.get("eof")
    if not isinstance(eof, bool):
        raise VerificationError("checkpoint EOF marker is invalid")
    return offset, stack, counts, eof


def _event_error(event_number, event, message):
    context = ""
    if _ACTIVE_EVENT_CONTEXT is not None:
        raw_box, contracted_box = _ACTIVE_EVENT_CONTEXT
        context = "; raw_box=%r; contracted_box=%r" % (raw_box, contracted_box)
    raise VerificationError(
        "trace event %d (opcode %d): %s%s"
        % (event_number, event, message, context)
    )


def _require_nonnegative(bound, event_number, event, rule):
    if bound is None or not (bound >= ZERO):
        _event_error(
            event_number,
            event,
            "%s did not certify a nonnegative lower bound; bound=%r"
            % (rule, bound),
        )


def _validate_tallies(counts, expected):
    if not isinstance(expected, dict) or set(expected) != set(TALLY_NAMES):
        raise VerificationError("expected replay tallies have the wrong fields")
    for name in TALLY_NAMES:
        value = expected[name]
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise VerificationError("expected replay tally %s is invalid" % name)
        if counts[name] != value:
            raise VerificationError(
                "trace tally mismatch for %s: expected %d, observed %d"
                % (name, value, counts[name])
            )


def replay_trace(trace_path, root_box, t_decimal, lambdas, *,
                 face_min_width=DEFAULT_FACE_MIN_WIDTH,
                 face_box_budget=DEFAULT_FACE_BOX_BUDGET,
                 center_lambdas=None, expected_tallies=None, max_events=None,
                 checkpoint_path=None, resume=False, checkpoint_binding=None):
    """Replay one-byte DFS events and independently verify every terminal.

    The return value contains the replay tallies, pending DFS depth, and EOF
    state.  It does not claim PASS; only :func:`audit_campaign_slice` may do so
    after authenticating the frozen inputs and exact expected tallies.
    """
    global _ACTIVE_EVENT_CONTEXT
    trace_path = Path(trace_path)
    root = _normalise_box(root_box)
    if isinstance(max_events, bool) or (
        max_events is not None
        and (not isinstance(max_events, int) or max_events < 0)
    ):
        raise VerificationError("max_events must be a nonnegative integer or None")
    if (isinstance(face_box_budget, bool)
            or not isinstance(face_box_budget, int) or face_box_budget <= 0):
        raise VerificationError("face_box_budget must be a positive integer")
    try:
        face_min_width = float(face_min_width)
    except (TypeError, ValueError, OverflowError) as exc:
        raise VerificationError("face_min_width must be positive and finite") from exc
    if not math.isfinite(face_min_width) or face_min_width <= 0:
        raise VerificationError("face_min_width must be positive and finite")

    try:
        lambda_texts = tuple(str(value) for value in lambdas)
    except TypeError as exc:
        raise VerificationError("lambda family must be iterable") from exc
    if not lambda_texts:
        raise VerificationError("lambda family must not be empty")
    if center_lambdas is None:
        center_texts = lambda_texts
    else:
        try:
            center_texts = tuple(str(value) for value in center_lambdas)
        except TypeError as exc:
            raise VerificationError("center lambda family must be iterable") from exc
        if not center_texts:
            raise VerificationError("center lambda family must not be empty")

    rh_cap, rho_cap, _ = _ensure_global_caps()
    previous = ctx.prec
    try:
        ctx.prec = REPLAY_PREC_BITS
        t = _a(str(t_decimal))
        if not t.is_finite():
            raise VerificationError("target is not finite")
        t_upper = target_upper_fraction(str(t_decimal))
        if str(t_decimal) == PINNED_TARGET and t_upper != PINNED_TARGET_UPPER:
            raise VerificationError("80-bit target upper endpoint differs from frozen geometry")
        lambda_values = tuple(_a(value) for value in lambda_texts)
        center_values = tuple(_a(value) for value in center_texts)
        if not all(value >= ZERO and value.is_finite() for value in lambda_values):
            raise VerificationError("every launch lambda must be finite and nonnegative")
        if not all(value >= ZERO and value.is_finite() for value in center_values):
            raise VerificationError("every center lambda must be finite and nonnegative")

        binding = checkpoint_binding or {
            "trace": str(trace_path.resolve()),
            "root": _serialise_box(root),
            "target": str(t_decimal),
            "lambdas": list(lambda_texts),
            "center_lambdas": list(center_texts),
            "face_min_width": repr(face_min_width),
            "face_box_budget": face_box_budget,
        }
        if resume:
            if checkpoint_path is None:
                raise VerificationError("resume requires a checkpoint path")
            offset, stack, counts, checkpoint_eof = _load_checkpoint(
                checkpoint_path, binding
            )
            if checkpoint_eof and stack:
                raise VerificationError("EOF checkpoint retains a pending stack")
        else:
            offset, stack, counts, checkpoint_eof = 0, [root], Counter(), False
        initial_trace_offset = offset

        if max_events is not None and offset > max_events:
            raise VerificationError("checkpoint is beyond requested max_events")
        try:
            trace_size = trace_path.stat().st_size
        except OSError as exc:
            raise VerificationError("cannot stat trace") from exc
        if offset > trace_size:
            raise VerificationError("checkpoint offset lies beyond trace EOF")
        if checkpoint_eof != (offset == trace_size):
            raise VerificationError("checkpoint EOF marker disagrees with trace size")

        stopped_by_limit = False
        try:
            trace = trace_path.open("rb")
        except OSError as exc:
            raise VerificationError("cannot open trace") from exc
        with trace:
            trace.seek(offset)
            while offset < trace_size:
                if max_events is not None and counts["processed"] >= max_events:
                    stopped_by_limit = True
                    break
                _ACTIVE_EVENT_CONTEXT = None
                encoded = trace.read(1)
                if len(encoded) != 1:
                    raise VerificationError("trace ended before its authenticated size")
                event = encoded[0]
                event_number = counts["processed"] + 1
                if event not in EVENT_NAMES:
                    _event_error(event_number, event, "unknown trace opcode")
                if not stack:
                    _event_error(event_number, event,
                                 "extra event after DFS stack exhaustion")

                raw = stack.pop()
                counts["processed"] += 1
                offset += 1
                box = contract_mean(raw, t_upper)
                _ACTIVE_EVENT_CONTEXT = (raw, box)

                if event == EVENT_MEAN_INFEASIBLE:
                    if box is not None:
                        _event_error(event_number, event,
                                     "mean contractor did not prove infeasibility")
                    counts["infeasible"] += 1
                elif box is None:
                    _event_error(event_number, event,
                                 "mean contractor proved infeasibility but opcode claims another outcome")
                elif event == EVENT_CORNER_INFEASIBLE:
                    if _corner_bound(box, t) is not None:
                        _event_error(event_number, event,
                                     "corner preparation did not prove infeasibility")
                    counts["infeasible"] += 1
                elif event == EVENT_CORNER:
                    _require_nonnegative(
                        _corner_bound(box, t), event_number, event, "corner rule"
                    )
                    counts["corner"] += 1
                elif event == EVENT_RATIO:
                    if not _ratio_rule(box, t, rho_cap):
                        _event_error(event_number, event,
                                     "decimal-outward ratio rule did not clear the box")
                    counts["ratio"] += 1
                elif event == EVENT_CENTER:
                    _require_nonnegative(
                        _best_centered(box, t, center_values, range(5), rh_cap),
                        event_number, event, "full centered AD rule",
                    )
                    counts["center"] += 1
                elif event == EVENT_CENTER_MIXED:
                    _require_nonnegative(
                        _best_centered(box, t, center_values, (0, 1, 4), rh_cap),
                        event_number, event, "mixed centered AD rule",
                    )
                    counts["center_mixed"] += 1
                elif event == EVENT_CENTER_MIXED_SWAP:
                    _require_nonnegative(
                        _best_centered(
                            _orbit_swap(box), t, center_values, (0, 1, 4), rh_cap
                        ), event_number, event, "swapped-mixed centered AD rule",
                    )
                    counts["center_mixed_swap"] += 1
                elif event == EVENT_CENTER_W:
                    _require_nonnegative(
                        _best_centered(box, t, center_values, (4,), rh_cap),
                        event_number, event, "weight-only centered AD rule",
                    )
                    counts["center_w"] += 1
                elif event == EVENT_FACE:
                    pinned = tuple(
                        lam for lam in lambda_values if _q2_pin(box, lam, rh_cap)
                    )
                    if not pinned:
                        _event_error(event_number, event,
                                     "endpoint derivative cap pinned no launch lambda")
                    face_box = (box[0], box[1], box[2], box[4])
                    complete, _ = _face_branch_and_bound(
                        face_box, t, pinned, rh_cap,
                        face_min_width, face_box_budget,
                    )
                    if not complete:
                        _event_error(event_number, event,
                                     "independent face branch-and-bound did not complete")
                    counts["face"] += 1
                elif event == EVENT_RESIDUAL:
                    _event_error(event_number, event,
                                 "residual leaf is invalid in a complete proof trace")
                elif EVENT_SPLIT_BASE <= event < EVENT_SPLIT_BASE + 5:
                    coordinate = event - EVENT_SPLIT_BASE
                    lo, hi = box[coordinate]
                    left, right = _split_box(box, coordinate)
                    midpoint = left[coordinate][1]
                    if (midpoint != right[coordinate][0]
                            or not (lo < midpoint < hi)):
                        _event_error(event_number, event,
                                     "split midpoint is not strict and representable")
                    stack.extend((left, right))
                    counts["split"] += 1
                else:
                    _event_error(event_number, event, "unsupported trace opcode")

                if (checkpoint_path is not None
                        and counts["processed"] % CHECKPOINT_INTERVAL == 0):
                    _write_checkpoint(
                        checkpoint_path, binding, offset, stack, counts,
                        offset == trace_size,
                    )
                    print(
                        "independent checkpoint: processed=%d pending=%d"
                        % (counts["processed"], len(stack)),
                        flush=True,
                    )

        eof = offset == trace_size
        accounted = sum(counts[name] for name in TALLY_NAMES if name != "processed")
        if accounted != counts["processed"]:
            raise VerificationError(
                "replay tallies account for %d of %d processed events"
                % (accounted, counts["processed"])
            )
        expected_pending = 1 + 2 * counts["split"] - counts["processed"]
        if expected_pending != len(stack):
            raise VerificationError(
                "DFS accounting predicts %d pending boxes, observed %d"
                % (expected_pending, len(stack))
            )
        if eof and counts["processed"] != 2 * counts["split"] + 1:
            raise VerificationError(
                "complete DFS trace violates processed=2*split+1"
            )
        if eof and stack:
            raise VerificationError(
                "trace ended after %d events with %d DFS boxes pending"
                % (counts["processed"], len(stack))
            )
        if not eof and not stopped_by_limit:
            raise VerificationError("trace replay stopped before EOF without an event limit")
        if eof and expected_tallies is not None:
            _validate_tallies(counts, expected_tallies)
        if checkpoint_path is not None:
            _write_checkpoint(checkpoint_path, binding, offset, stack, counts, eof)

        result = {name: int(counts[name]) for name in TALLY_NAMES}
        result.update({
            "pending_stack": len(stack),
            "trace_offset": offset,
            "eof": eof,
            "tallies_verified": bool(eof and expected_tallies is not None),
            "initial_trace_offset": initial_trace_offset,
            "resume_used": bool(resume),
        })
        return result
    finally:
        ctx.prec = previous


