def _a(value):
    """Construct an outward Arb value using decimal semantics for floats."""
    if isinstance(value, arb):
        return arb(value)
    if isinstance(value, bool):
        raise VerificationError("boolean is not an Arb scalar")
    if isinstance(value, Fraction):
        return arb(value.numerator) / arb(value.denominator)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise VerificationError("non-finite Arb scalar")
        return arb(repr(value))
    return arb(str(value))


def _hull(*values):
    if not values:
        raise VerificationError("empty interval hull")
    result = _a(values[0])
    for value in values[1:]:
        result = result.union(_a(value))
    return result


def _amin(left, right):
    left, right = _a(left), _a(right)
    if left <= right:
        return left
    if right <= left:
        return right
    return _hull(left, right)


def _amax(left, right):
    left, right = _a(left), _a(right)
    if left >= right:
        return left
    if right >= left:
        return right
    return _hull(left, right)


def _abs_upper(value):
    value = _a(value)
    return _amax(-value.lower(), value.upper()).upper()


def _is_zero(value):
    value = _a(value)
    return bool(value.is_exact() and value == ZERO)


def _h_point(value):
    value = _a(value)
    if value <= ZERO or value >= ONE:
        return ZERO
    return -(value * value.log() + (ONE - value) * (ONE - value).log()) / LOG2


def _h_range(lower, upper):
    lower, upper = _a(lower), _a(upper)
    endpoints = _hull(_h_point(lower), _h_point(upper))
    if upper <= HALF or lower >= HALF:
        return endpoints
    return _hull(endpoints, ONE)


def _h_prime(lower, upper):
    lower, upper = _a(lower), _a(upper)
    if not (lower > ZERO and upper < ONE):
        return None
    low_value = ((ONE - upper).log() - upper.log()) / LOG2
    high_value = ((ONE - lower).log() - lower.log()) / LOG2
    return _hull(low_value, high_value)


def _sstar_point(p, q):
    p, q = _a(p), _a(q)
    return _amin(_amax(HALF, _amax(p, q)), _amin(p + q, ONE))


def _sstar_range(pl, ph, ql, qh):
    return _hull(_sstar_point(pl, ql), _sstar_point(ph, qh))


def _rh_range(lower, upper, global_cap=None):
    lower, upper = _a(lower), _a(upper)
    z = _hull(lower, upper)
    hz = _h_range(lower, upper)
    x_lower = (ONE - upper) * (ONE - upper)
    x_upper = (ONE - lower) * (ONE - lower)
    transformed = _h_range(x_lower, x_upper)
    raw = TWO * (ONE - z) * hz - transformed
    lo = _amax(raw.lower(), ZERO)
    hi = _amax(raw.upper(), ZERO)
    if global_cap is not None:
        hi = _amin(hi, global_cap)
    return _hull(lo, hi)


def _sqrt_rh_range(lower, upper, global_cap=None):
    enclosure = _rh_range(lower, upper, global_cap)
    lo = enclosure.lower()
    sqrt_lo = lo.sqrt() if lo > ZERO else ZERO
    hi = _amax(enclosure.upper(), ZERO).upper()
    return _hull(sqrt_lo, hi.sqrt())


def _rh_prime(lower, upper):
    lower, upper = _a(lower), _a(upper)
    hp = _h_prime(lower, upper)
    x_lower = (ONE - upper) * (ONE - upper)
    x_upper = (ONE - lower) * (ONE - lower)
    hp2 = _h_prime(x_lower, x_upper)
    if hp is None or hp2 is None:
        return None
    z = _hull(lower, upper)
    return -TWO * _h_range(lower, upper) + TWO * (ONE - z) * (hp + hp2)


def _positive_rh_range(lower, upper, global_cap):
    lower, upper = _a(lower), _a(upper)
    if not (lower > ZERO and upper < ONE):
        return None
    direct = _rh_range(lower, upper, global_cap)
    if direct.lower() > ZERO:
        return direct
    for subdivisions in (8, 32, 128):
        step = (upper - lower) / subdivisions
        pieces = []
        for index in range(subdivisions):
            left = lower + index * step
            right = lower + (index + 1) * step
            piece = _rh_range(left, right, global_cap)
            if not (piece.lower() > ZERO):
                pieces = None
                break
            pieces.append(piece)
        if pieces is not None:
            return _hull(*pieces)
    return None


def _sqrt_rh_prime(lower, upper, global_cap):
    positive = _positive_rh_range(lower, upper, global_cap)
    derivative = _rh_prime(lower, upper)
    if positive is None or derivative is None:
        return None
    root = positive.sqrt()
    if not root.is_finite() or not (root.lower() > ZERO):
        return None
    result = derivative / (TWO * root)
    return result if result.is_finite() else None


def _rh_global_cover(cells):
    best = ZERO
    for index in range(cells):
        lower = arb(index) / cells
        upper = arb(index + 1) / cells
        cell = _rh_range(lower, upper).upper()
        if not (cell <= best):
            best = _amax(best, cell)
    return best.upper()


def _rho_direct_upper(lower, upper):
    lower, upper = _a(lower), _a(upper)
    transformed_lower = TWO * lower - lower * lower
    transformed_upper = TWO * upper - upper * upper
    numerator_lo = _h_range(transformed_lower, transformed_upper).lower()
    denominator_hi = _h_range(lower, upper).upper()
    return (TWO * (ONE - lower) - numerator_lo / denominator_hi).upper()


def _rho_global_cover(cells):
    if cells < 4:
        raise VerificationError("rho cover requires at least four cells")
    best = ZERO
    for index in range(cells):
        lower = arb(index) / cells
        upper = arb(index + 1) / cells
        candidates = []
        if lower > ZERO and upper < ONE:
            candidates.append(_rho_direct_upper(lower, upper))
        if upper <= HALF and upper > ZERO:
            candidates.append((TWO * upper / _h_point(upper)).upper())
        elif lower >= HALF and lower < ONE:
            candidates.append((TWO * (ONE - lower) / _h_point(lower)).upper())
        if not candidates:
            raise VerificationError("rho cover produced an uncapped cell")
        cell = candidates[0]
        for candidate in candidates[1:]:
            cell = _amin(cell, candidate)
        if not (cell <= best):
            best = _amax(best, cell)
    return best.upper()


def _endpoint_derivative_cap():
    x = arb(1) / 16
    q = ((ONE - x) * (TWO - arb(3) * x + x * x)
         / (TWO * (ONE - x)))
    if not (q > ZERO):
        raise VerificationError("endpoint derivative lemma lost positivity")
    return (ONE / ((ONE - x) * (LOG2 * q).sqrt())).upper()


def _ensure_global_caps():
    global _RH_GLOBAL_CAP, _RHO_GLOBAL_CAP, _DQ_ENDPOINT_CAP
    if (_RH_GLOBAL_CAP is not None and _RHO_GLOBAL_CAP is not None
            and _DQ_ENDPOINT_CAP is not None):
        return _RH_GLOBAL_CAP, _RHO_GLOBAL_CAP, _DQ_ENDPOINT_CAP
    previous = ctx.prec
    try:
        ctx.prec = NATIVE_PREC_BITS
        rh_cap = _rh_global_cover(GLOBAL_COVER_CELLS)
        rho_cap = _rho_global_cover(GLOBAL_COVER_CELLS)
        dq_cap = _endpoint_derivative_cap()
        if not (rh_cap >= arb("0.2342294") and rh_cap <= arb("0.2350")):
            raise VerificationError("independent rh cover failed its locked range")
        if not (rho_cap > ZERO and rho_cap.is_finite()):
            raise VerificationError("independent rho cover is not finite and positive")
        if not (dq_cap > arb("1.2") and dq_cap < arb("1.4")):
            raise VerificationError("endpoint derivative cap failed its locked range")
        _RH_GLOBAL_CAP, _RHO_GLOBAL_CAP, _DQ_ENDPOINT_CAP = rh_cap, rho_cap, dq_cap
    finally:
        ctx.prec = previous
    return _RH_GLOBAL_CAP, _RHO_GLOBAL_CAP, _DQ_ENDPOINT_CAP


def _rho_upper(lower, upper, global_cap):
    lower, upper = _a(lower), _a(upper)
    cap = _a(global_cap)
    if lower > ZERO and upper < ONE:
        cap = _amin(cap, _rho_direct_upper(lower, upper))
    if upper <= HALF and upper > ZERO:
        cap = _amin(cap, (TWO * upper / _h_point(upper)).upper())
    elif lower >= HALF and lower < ONE:
        cap = _amin(cap, (TWO * (ONE - lower) / _h_point(lower)).upper())
    return _amax(cap, ZERO).upper()


