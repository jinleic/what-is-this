class AD:
    """An Arb interval value with an interval gradient vector."""

    __slots__ = ("value", "gradient")

    def __init__(self, value, gradient):
        self.value = _a(value)
        self.gradient = tuple(_a(component) for component in gradient)

    @classmethod
    def constant(cls, value, dimension):
        return cls(value, (ZERO,) * dimension)

    @classmethod
    def variable(cls, value, dimension, coordinate):
        gradient = [ZERO] * dimension
        gradient[coordinate] = ONE
        return cls(value, gradient)

    def _coerce(self, other):
        if isinstance(other, AD):
            if len(other.gradient) != len(self.gradient):
                raise VerificationError("automatic-differentiation dimensions differ")
            return other
        return AD.constant(other, len(self.gradient))

    def __add__(self, other):
        other = self._coerce(other)
        return AD(self.value + other.value,
                  (left + right for left, right in zip(self.gradient, other.gradient)))

    __radd__ = __add__

    def __neg__(self):
        return AD(-self.value, (-component for component in self.gradient))

    def __sub__(self, other):
        return self + (-self._coerce(other))

    def __rsub__(self, other):
        return self._coerce(other) - self

    def __mul__(self, other):
        other = self._coerce(other)
        return AD(
            self.value * other.value,
            (left * other.value + self.value * right
             for left, right in zip(self.gradient, other.gradient)),
        )

    __rmul__ = __mul__

    def __truediv__(self, other):
        other = self._coerce(other)
        denominator = other.value * other.value
        return AD(
            self.value / other.value,
            ((left * other.value - self.value * right) / denominator
             for left, right in zip(self.gradient, other.gradient)),
        )

    def __rtruediv__(self, other):
        return self._coerce(other) / self

    def __pow__(self, exponent):
        if exponent != 2:
            raise VerificationError("AD only needs the square operation")
        return self * self


def _ad_all_constant(value):
    return all(_is_zero(component) for component in value.gradient)


def _ad_entropy(value, domain=None):
    lower, upper = (
        domain if domain is not None
        else (value.value.lower(), value.value.upper())
    )
    enclosure = _h_range(lower, upper)
    if _ad_all_constant(value):
        return AD(enclosure, (ZERO,) * len(value.gradient))
    derivative = _h_prime(lower, upper)
    if derivative is None:
        return None
    return AD(enclosure, (derivative * component for component in value.gradient))


def _ad_sqrt_rh(value, global_cap, domain=None):
    lower, upper = (
        domain if domain is not None
        else (value.value.lower(), value.value.upper())
    )
    enclosure = _sqrt_rh_range(lower, upper, global_cap)
    if _ad_all_constant(value):
        return AD(enclosure, (ZERO,) * len(value.gradient))
    derivative = _sqrt_rh_prime(lower, upper, global_cap)
    if derivative is None:
        return None
    return AD(enclosure, (derivative * component for component in value.gradient))


def _sstar_affine_branch(pl, ph, ql, qh):
    if ph <= HALF and qh <= HALF:
        upper_branch = (HALF, HALF, ZERO, ZERO)
    elif pl >= HALF and pl >= qh:
        upper_branch = (pl, ph, ONE, ZERO)
    elif ql >= HALF and ql >= ph:
        upper_branch = (ql, qh, ZERO, ONE)
    else:
        return None

    if ph + qh <= ONE:
        lower_branch = (pl + ql, ph + qh, ONE, ONE)
    elif pl + ql >= ONE:
        lower_branch = (ONE, ONE, ZERO, ZERO)
    else:
        return None

    if upper_branch[1] <= lower_branch[0]:
        return upper_branch
    if lower_branch[1] <= upper_branch[0]:
        return lower_branch
    return None


def _ad_sstar(p, q, p_domain=None, q_domain=None):
    pl, ph = p_domain if p_domain is not None else (
        p.value.lower(), p.value.upper()
    )
    ql, qh = q_domain if q_domain is not None else (
        q.value.lower(), q.value.upper()
    )
    branch = _sstar_affine_branch(pl, ph, ql, qh)
    if branch is not None:
        lower, upper, dp, dq = branch
        result = AD(
            _hull(lower, upper),
            (dp * pg + dq * qg for pg, qg in zip(p.gradient, q.gradient)),
        )
        return result, (lower, upper)

    value = _sstar_range(pl, ph, ql, qh)
    domain = (value.lower(), value.upper())
    if _ad_all_constant(p) and _ad_all_constant(q):
        return AD(value, (ZERO,) * len(p.gradient)), domain

    # At differentiability points the clipped median has one of the gradients
    # 0, grad(p), grad(q), or grad(p)+grad(q).  Their interval hull therefore
    # encloses every a.e. directional derivative needed by the MVT argument.
    gradient = []
    for pg, qg in zip(p.gradient, q.gradient):
        gradient.append(_hull(ZERO, pg, qg, pg + qg))
    return AD(value, gradient), domain


def _normalise_box(box):
    try:
        coordinates = tuple(box)
    except TypeError as exc:
        raise VerificationError("box must be iterable") from exc
    if len(coordinates) != 5:
        raise VerificationError("box must contain exactly five intervals")
    result = []
    for coordinate, pair in enumerate(coordinates):
        try:
            endpoints = tuple(pair)
        except TypeError as exc:
            raise VerificationError("box coordinate is not iterable") from exc
        if len(endpoints) != 2:
            raise VerificationError("box coordinate must have two endpoints")
        try:
            lo, hi = float(endpoints[0]), float(endpoints[1])
        except (TypeError, ValueError, OverflowError) as exc:
            raise VerificationError("box endpoint is not numeric") from exc
        if not (math.isfinite(lo) and math.isfinite(hi)):
            raise VerificationError("box endpoint is not finite")
        if not (0.0 <= lo <= hi <= 1.0):
            raise VerificationError(
                "box coordinate %d is reversed or outside [0,1]" % coordinate
            )
        result.append((lo, hi))
    return tuple(result)


def _prepare_box(box):
    pairs = [(_a(lo), _a(hi)) for lo, hi in box]
    pairs[1] = (_amax(pairs[1][0], pairs[0][0]), pairs[1][1])
    pairs[3] = (_amax(pairs[3][0], pairs[2][0]), pairs[3][1])
    if pairs[1][0] > pairs[1][1] or pairs[3][0] > pairs[3][1]:
        return None
    return tuple(pairs)


def _phi_ad_from_pairs(pairs, t, lam, active_coordinates, global_cap):
    active_coordinates = tuple(active_coordinates)
    dimensions = {coordinate: position
                  for position, coordinate in enumerate(active_coordinates)}
    dimension = len(active_coordinates)
    values = []
    for coordinate, (lower, upper) in enumerate(pairs):
        interval = _hull(lower, upper)
        if coordinate in dimensions:
            values.append(AD.variable(interval, dimension, dimensions[coordinate]))
        else:
            values.append(AD.constant(interval, dimension))
    p1, q1, p2, q2, weight = values
    complement = -weight + ONE

    hp1, hq1 = _ad_entropy(p1, pairs[0]), _ad_entropy(q1, pairs[1])
    hp2, hq2 = _ad_entropy(p2, pairs[2]), _ad_entropy(q2, pairs[3])
    if any(value is None for value in (hp1, hq1, hp2, hq2)):
        return None
    s1, s1_domain = _ad_sstar(p1, q1, pairs[0], pairs[1])
    s2, s2_domain = _ad_sstar(p2, q2, pairs[2], pairs[3])
    c1, c2 = _ad_entropy(s1, s1_domain), _ad_entropy(s2, s2_domain)
    if c1 is None or c2 is None:
        return None
    rp1 = _ad_sqrt_rh(p1, global_cap, pairs[0])
    rq1 = _ad_sqrt_rh(q1, global_cap, pairs[1])
    rp2 = _ad_sqrt_rh(p2, global_cap, pairs[2])
    rq2 = _ad_sqrt_rh(q2, global_cap, pairs[3])
    if any(value is None for value in (rp1, rq1, rp2, rq2)):
        return None

    m1, m2 = (p1 + q1) / TWO, (p2 + q2) / TWO
    l1, l2 = (hp1 + hq1) / TWO, (hp2 + hq2) / TWO
    u1, u2 = (rp1 + rq1) / TWO, (rp2 + rq2) / TWO
    mean = weight * m1 + complement * m2
    entropy = weight * l1 + complement * l2
    correction = weight * c1 + complement * c2
    sigma = weight * u1 + complement * u2
    coefficient = (-mean + ONE) * (TWO * BETA) - ONE
    result = (coefficient * entropy + correction * ALPHA
              - sigma * sigma * BETA + (mean - _a(t)) * _a(lam))
    if not result.value.is_finite():
        return None
    if not all(component.is_finite() for component in result.gradient):
        return None
    return result


def ad_gradient(box, t_decimal, lambda_value):
    """Return the independently generated five-component interval gradient."""
    normalised = _normalise_box(box)
    global_cap, _, _ = _ensure_global_caps()
    previous = ctx.prec
    try:
        ctx.prec = REPLAY_PREC_BITS
        prepared = _prepare_box(normalised)
        if prepared is None:
            return None
        lam = _a(lambda_value)
        if not (lam >= ZERO):
            raise VerificationError("lambda must be certified nonnegative")
        result = _phi_ad_from_pairs(
            prepared, _a(str(t_decimal)), lam, range(5), global_cap
        )
        return None if result is None else result.gradient
    finally:
        ctx.prec = previous


def _centered_bound(pairs, t, lam, active_coordinates, global_cap):
    active_coordinates = tuple(active_coordinates)
    derivative_ad = _phi_ad_from_pairs(
        pairs, t, lam, active_coordinates, global_cap
    )
    if derivative_ad is None:
        return None
    anchor = list(pairs)
    radii = []
    for coordinate in active_coordinates:
        lower, upper = pairs[coordinate]
        midpoint = (lower + upper) / TWO
        anchor[coordinate] = (midpoint, midpoint)
        radii.append((upper - lower) / TWO)
    anchor_ad = _phi_ad_from_pairs(anchor, t, lam, (), global_cap)
    if anchor_ad is None:
        return None
    penalty = ZERO
    for derivative, radius in zip(derivative_ad.gradient, radii):
        penalty += _abs_upper(derivative) * radius
    lower = _a(anchor_ad.value.lower()) - penalty
    return lower if lower.is_finite() else None


def _best_centered(box, t, lambdas, active_coordinates, global_cap):
    prepared = _prepare_box(box)
    if prepared is None:
        return None
    best = None
    for lam in lambdas:
        bound = _centered_bound(
            prepared, t, lam, active_coordinates, global_cap
        )
        if bound is not None and (best is None or bound > best):
            best = bound
    return best


def _orbit_swap(box):
    wl, wh = _a(box[4][0]), _a(box[4][1])
    return (
        box[2],
        box[3],
        box[0],
        box[1],
        ((ONE - wh).lower(), (ONE - wl).upper()),
    )


