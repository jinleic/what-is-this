def _corner_bound(box, t):
    (p1l, p1h), (q1l, q1h), (p2l, p2h), (q2l, q2h), (wl, wh) = box
    q1l, q2l = max(q1l, p1l), max(q2l, p2l)
    if q1l > q1h or q2l > q2h:
        return None

    p1lo, p1hi = _a(p1l), _a(p1h)
    q1lo, q1hi = _a(q1l), _a(q1h)
    p2lo, p2hi = _a(p2l), _a(p2h)
    q2lo, q2hi = _a(q2l), _a(q2h)
    weight = _hull(_a(wl), _a(wh))
    m1 = _hull((p1lo + q1lo) / TWO, (p1hi + q1hi) / TWO)
    m2 = _hull((p2lo + q2lo) / TWO, (p2hi + q2hi) / TWO)
    mean = weight * m1 + (ONE - weight) * m2
    if mean.lower() > t:
        return None
    m_cap = _amin(mean.upper(), t)
    coefficient = TWO * BETA * (ONE - m_cap) - ONE
    if not (coefficient > ZERO):
        return arb(-1)

    entropy = (
        weight * (_h_float_range(p1l, p1h) + _h_float_range(q1l, q1h)) / TWO
        + (ONE - weight)
        * (_h_float_range(p2l, p2h) + _h_float_range(q2l, q2h)) / TWO
    )
    entropy_lo = _amax(entropy.lower(), ZERO)
    correction = (
        weight * _sstar_h_float_range(p1l, p1h, q1l, q1h)
        + (ONE - weight) * _sstar_h_float_range(p2l, p2h, q2l, q2h)
    )
    correction_lo = _amax(correction.lower(), ZERO)
    sigma1 = (
        _sqrt_rh_float_range(p1l, p1h)
        + _sqrt_rh_float_range(q1l, q1h)
    ) / TWO
    sigma2 = (
        _sqrt_rh_float_range(p2l, p2h)
        + _sqrt_rh_float_range(q2l, q2h)
    ) / TWO
    sigma_hi = (weight * sigma1 + (ONE - weight) * sigma2).upper()
    return (coefficient * entropy_lo + ALPHA * correction_lo
            - BETA * sigma_hi * sigma_hi)


def _ratio_rule(box, t, rho_global_cap):
    weight = _hull(_a(box[4][0]), _a(box[4][1]))
    arho = (
        _rho_float_upper(box[0][0], box[0][1])
        + _rho_float_upper(box[1][0], box[1][1])
    ) / TWO
    brho = (
        _rho_float_upper(box[2][0], box[2][1])
        + _rho_float_upper(box[3][0], box[3][1])
    ) / TWO
    wl, wh = weight.lower(), weight.upper()
    at_lo = (ONE - wl) * brho + wl * arho
    at_hi = (ONE - wh) * brho + wh * arho
    rho_hi = _amax(at_lo.upper(), at_hi.upper())
    kappa = TWO * BETA * (ONE - t) - ONE
    return bool(kappa - BETA * rho_hi >= ZERO)


def _dq_upper(q2_lower):
    _, _, cap = _ensure_global_caps()
    q2_lower = _a(q2_lower)
    if not (q2_lower >= ONE - arb(1) / 16):
        return None
    return cap


def _q2_pin(box, lam, global_cap):
    (p1l, p1h), (q1l, q1h), (p2l, p2h), (q2l, q2h), (wl, wh) = box
    q2l = max(q2l, p2l)
    if q2l > q2h or Fraction(repr(q2l)) < Q2_PIN or p2h > q2l:
        return False
    derivative_cap = _dq_upper(q2l)
    if derivative_cap is None:
        return False

    p1lo, p1hi = _a(p1l), _a(p1h)
    q1lo, q1hi = _a(q1l), _a(q1h)
    p2lo, p2hi = _a(p2l), _a(p2h)
    q2lo = _a(q2l)
    q1lo = _amax(q1lo, p1lo)
    if q1lo > q1hi:
        return True

    weight = _hull(_a(wl), _a(wh))
    complement = ONE - weight
    m1 = _hull((p1lo + q1lo) / TWO, (p1hi + q1hi) / TWO)
    m2 = _hull((p2lo + q2lo) / TWO, (p2hi + ONE) / TWO)
    mean = weight * m1 + complement * m2
    coefficient_lo = (TWO * BETA * (ONE - mean) - ONE).lower()
    if not (coefficient_lo > ZERO):
        return False

    entropy_prime_at_lower = ((ONE - q2lo).log() - q2lo.log()) / LOG2
    complement_lo = _amax(ONE - _a(wh), ZERO)
    complement_hi = _amin(ONE - _a(wl), ONE)
    negative_upper = (
        coefficient_lo * complement_lo / TWO + ALPHA * complement_lo
    ) * entropy_prime_at_lower
    sigma = (
        weight
        * (_sqrt_rh_range(p1lo, p1hi, global_cap)
           + _sqrt_rh_range(q1lo, q1hi, global_cap))
        / TWO
        + complement
        * (_sqrt_rh_range(p2lo, p2hi, global_cap)
           + _sqrt_rh_range(q2lo, ONE, global_cap))
        / TWO
    )
    positive_upper = (
        BETA * sigma.upper() * complement_hi * derivative_cap
        + _a(lam) * complement_hi / TWO
    )
    # The omitted coefficient derivative is -beta*(1-w)*L and is nonpositive.
    return bool(negative_upper + positive_upper <= ZERO)


def _face_pairs(face_box):
    p1, q1, p2, weight = face_box
    return _prepare_box((p1, q1, p2, (1.0, 1.0), weight))


def _face_best_bound(face_box, t, lambdas, global_cap):
    pairs = _face_pairs(face_box)
    if pairs is None:
        return None
    best = None
    for lam in lambdas:
        natural = _phi_ad_from_pairs(pairs, t, lam, (), global_cap)
        if natural is not None:
            candidate = _a(natural.value.lower())
            if best is None or candidate > best:
                best = candidate
        centered = _centered_bound(pairs, t, lam, (0, 1, 2, 4), global_cap)
        if centered is not None and (best is None or centered > best):
            best = centered
    return best


def _split_box(box, coordinate):
    lo, hi = box[coordinate]
    midpoint = (lo + hi) / 2.0
    left, right = list(box), list(box)
    left[coordinate] = (lo, midpoint)
    right[coordinate] = (midpoint, hi)
    return tuple(left), tuple(right)


def _face_branch_and_bound(face_box, t, lambdas, global_cap,
                           min_width, box_budget):
    stack = [face_box]
    counts = Counter()
    while stack:
        if counts["processed"] >= box_budget:
            counts["budget"] += len(stack)
            return False, counts
        box = stack.pop()
        counts["processed"] += 1
        bound = _face_best_bound(box, t, lambdas, global_cap)
        if bound is not None and bound >= ZERO:
            counts["cleared"] += 1
            continue
        widths = [hi - lo for lo, hi in box]
        widest = max(range(4), key=widths.__getitem__)
        if widths[widest] <= min_width:
            counts["residual"] += 1
            return False, counts
        left, right = _split_box(box, widest)
        stack.extend((left, right))
        counts["split"] += 1
    return True, counts


