def _fraction_from_exact_arb(value):
    point = arb(value)
    if not point.is_exact():
        raise VerificationError("expected an exact Arb point")
    mantissa, exponent = point.man_exp()
    mantissa, exponent = int(mantissa), int(exponent)
    if exponent >= 0:
        return Fraction(mantissa) * (2**exponent)
    return Fraction(mantissa, 2 ** (-exponent))


def _decimal_fraction(value):
    if isinstance(value, bool):
        raise VerificationError("boolean is not a numeric endpoint")
    if isinstance(value, Fraction):
        return value
    if isinstance(value, int):
        return Fraction(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise VerificationError("non-finite numeric endpoint")
        return Fraction(repr(value))
    if isinstance(value, arb):
        return _fraction_from_exact_arb(value)
    try:
        return Fraction(str(value))
    except (ValueError, TypeError, ZeroDivisionError) as exc:
        raise VerificationError("invalid exact numeric endpoint") from exc


def next_decimal_up(value):
    """Least nearby float whose shortest decimal denotes at least ``value``."""
    target = _decimal_fraction(value)
    candidate = float(target)
    if not math.isfinite(candidate):
        raise VerificationError("decimal cutoff does not fit in a finite float")
    while Fraction(repr(candidate)) < target:
        candidate = math.nextafter(candidate, math.inf)
    return candidate


def _next_decimal_down(value):
    target = _decimal_fraction(value)
    candidate = float(target)
    if not math.isfinite(candidate):
        raise VerificationError("decimal cutoff does not fit in a finite float")
    while Fraction(repr(candidate)) > target:
        candidate = math.nextafter(candidate, -math.inf)
    return candidate


def target_upper_fraction(t_decimal):
    """Return the exact 80-bit Arb upper endpoint used by Campaign I geometry."""
    text = str(t_decimal)
    try:
        rational = Fraction(text)
    except (ValueError, TypeError, ZeroDivisionError) as exc:
        raise VerificationError("target must be a finite decimal rational") from exc
    if rational < 0 or rational > 1:
        raise VerificationError("target must lie in [0,1]")
    previous = ctx.prec
    try:
        ctx.prec = REPLAY_PREC_BITS
        target = arb(text)
        if not target.is_finite():
            raise VerificationError("target did not produce a finite Arb ball")
        return _fraction_from_exact_arb(target.upper())
    finally:
        ctx.prec = previous


def contract_mean(box, t_upper):
    """Contract the weight using exact decimal/Fraction arithmetic.

    A trace endpoint is interpreted as the rational denoted by its shortest
    decimal representation.  ``t_upper`` must be the permissive 80-bit Arb
    upper endpoint, not the exact target decimal; this distinction fixes the
    DFS geometry of the frozen trace.
    """
    coordinates = tuple(box)
    if len(coordinates) != 5:
        raise VerificationError("mean contractor requires a five-dimensional box")
    pairs = []
    for coordinate, pair in enumerate(coordinates):
        endpoints = tuple(pair)
        if len(endpoints) != 2:
            raise VerificationError(
                "box coordinate %d is not a two-endpoint interval" % coordinate
            )
        lo, hi = endpoints
        if _decimal_fraction(lo) > _decimal_fraction(hi):
            raise VerificationError("box interval is reversed")
        pairs.append((lo, hi))

    l1 = (_decimal_fraction(pairs[0][0]) + _decimal_fraction(pairs[1][0])) / 2
    l2 = (_decimal_fraction(pairs[2][0]) + _decimal_fraction(pairs[3][0])) / 2
    t_cap = _decimal_fraction(t_upper)
    wl, wh = pairs[4]

    if l1 > t_cap and l2 > t_cap:
        return None

    new_wl, new_wh = float(wl), float(wh)
    if l1 > t_cap >= l2:
        cutoff = (t_cap - l2) / (l1 - l2)
        new_wh = min(new_wh, next_decimal_up(cutoff))
    elif l2 > t_cap >= l1:
        cutoff = (l2 - t_cap) / (l2 - l1)
        new_wl = max(new_wl, _next_decimal_down(cutoff))

    if Fraction(repr(new_wl)) > Fraction(repr(new_wh)):
        return None
    if new_wl == float(wl) and new_wh == float(wh):
        return tuple((float(lo), float(hi)) for lo, hi in pairs)
    result = [(float(lo), float(hi)) for lo, hi in pairs]
    result[4] = (new_wl, new_wh)
    return tuple(result)


