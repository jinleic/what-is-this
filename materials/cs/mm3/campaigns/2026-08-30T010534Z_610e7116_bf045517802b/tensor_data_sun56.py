def parse_blocks(text):
    blocks = []
    cur = []
    for line in text.strip().splitlines():
        line = line.strip()
        if line == "#":
            blocks.append(cur)
            cur = []
        elif line:
            cur.append([int(x) for x in line.split()])
    blocks.append(cur)
    assert len(blocks) == 3 and all(len(b) == 9 and all(len(r) == 23 for r in b) for b in blocks)
    return blocks
